"""Generate a FlatZinc community detection benchmark.

Produces a problem similar to "mexican.s26.k4" from MiniZinc Challenge 2024,
but with 12 nodes and k=4 clusters. The model:

  - Each node i gets a cluster assignment c_i in 1..k
  - For each edge (i,j) with weight w_ij, a boolean same_ij indicates
    whether c_i == c_j (via int_eq_reif decomposition)
  - Objective = sum of w_ij * same_ij (maximize intra-cluster weight)
  - Symmetry breaking: lex ordering on cluster indicator columns

Author: Andrew Yates <andrewyates.name@gmail.com>
"""

import random
import os

# Parameters
N = 12       # nodes
K = 4        # clusters
SEED = 42    # reproducibility
EDGE_PROB = 0.5  # probability of edge between any pair
W_MIN = 1
W_MAX = 50
TARGET_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(TARGET_DIR, "community_detect_test.fzn")

random.seed(SEED)

# Generate edges with random weights
edges = []  # (i, j, weight) with i < j, 1-indexed
for i in range(1, N + 1):
    for j in range(i + 1, N + 1):
        if random.random() < EDGE_PROB:
            w = random.randint(W_MIN, W_MAX)
            edges.append((i, j, w))

total_weight = sum(w for _, _, w in edges)
print(f"Generated {len(edges)} edges with total weight {total_weight}")

# Ensure total weight is in the 200-300 range; scale if needed
if total_weight < 200:
    scale = 200.0 / total_weight
    edges = [(i, j, max(1, int(w * scale + 0.5))) for i, j, w in edges]
    total_weight = sum(w for _, _, w in edges)
elif total_weight > 300:
    scale = 250.0 / total_weight
    edges = [(i, j, max(1, int(w * scale + 0.5))) for i, j, w in edges]
    total_weight = sum(w for _, _, w in edges)

print(f"After scaling: {len(edges)} edges, total weight {total_weight}")

lines = []

# Header comment
lines.append(f"% Community Detection: {N} nodes, {K} clusters, {len(edges)} edges")
lines.append(f"% Total edge weight: {total_weight}")
lines.append(f"% Generated by gen_community.py (seed={SEED})")
lines.append("")

# Node cluster assignment variables: c1..cN in 1..K
for i in range(1, N + 1):
    lines.append(f"var 1..{K}: c{i} :: output_var;")
lines.append("")

# For each edge (i,j), we need:
#   diff_eid = c_i - c_j           (via int_lin_eq)
#   same_eid <-> (diff_eid == 0)   (via int_eq_reif)
#   isame_eid = bool2int(same_eid) (via bool2int)

# Declare edge auxiliary variables
for idx, (i, j, w) in enumerate(edges):
    eid = f"e{i}_{j}"
    lo = 1 - K  # minimum difference
    hi = K - 1  # maximum difference
    lines.append(f"var {lo}..{hi}: diff_{eid} :: var_is_introduced;")
    lines.append(f"var bool: same_{eid} :: var_is_introduced;")
    lines.append(f"var 0..1: isame_{eid} :: var_is_introduced;")
lines.append("")

# Objective variable: sum of w_ij * isame_ij
# Max possible = total_weight (all edges intra-cluster)
lines.append(f"var 0..{total_weight}: obj :: output_var;")
lines.append("")

# Constraints for each edge
lines.append("% Edge constraints: diff = ci - cj, same <-> diff==0, isame = bool2int(same)")
for idx, (i, j, w) in enumerate(edges):
    eid = f"e{i}_{j}"
    # diff_eid = c_i - c_j
    lines.append(
        f"constraint int_lin_eq([1, -1, -1], [c{i}, c{j}, diff_{eid}], 0);"
    )
    # same_eid <-> diff_eid == 0
    lines.append(
        f"constraint int_eq_reif(diff_{eid}, 0, same_{eid});"
    )
    # isame_eid = bool2int(same_eid)
    lines.append(
        f"constraint bool2int(same_{eid}, isame_{eid});"
    )
lines.append("")

# Objective: obj = sum(w_ij * isame_ij)
# int_lin_eq([w1, w2, ..., -1], [isame_1, isame_2, ..., obj], 0)
lines.append("% Objective: obj = sum of w_ij * isame_ij")
coeffs = [str(w) for _, _, w in edges] + ["-1"]
vars_ = [f"isame_e{i}_{j}" for i, j, _ in edges] + ["obj"]
lines.append(
    f"constraint int_lin_eq([{', '.join(coeffs)}], [{', '.join(vars_)}], 0);"
)
lines.append("")

# Symmetry breaking via fzn_lex_lesseq_int on cluster indicator columns.
#
# For each cluster v in 1..K, define indicator column:
#   ind_v_i <-> (c_i == v), iind_v_i = bool2int(ind_v_i)
# Then: fzn_lex_lesseq_int(ind_{v+1}, ind_v) for v in 1..K-1
# (later cluster indicators are lex-less-or-equal to earlier ones)

lines.append("% Cluster indicator variables for symmetry breaking")
for v in range(1, K + 1):
    for i in range(1, N + 1):
        lines.append(f"var bool: ind_{v}_{i} :: var_is_introduced;")
        lines.append(f"var 0..1: iind_{v}_{i} :: var_is_introduced;")
lines.append("")

lines.append("% Indicator definitions: ind_v_i <-> (c_i == v)")
for v in range(1, K + 1):
    for i in range(1, N + 1):
        lines.append(f"constraint int_eq_reif(c{i}, {v}, ind_{v}_{i});")
        lines.append(
            f"constraint bool2int(ind_{v}_{i}, iind_{v}_{i});"
        )
lines.append("")

# Symmetry breaking: lex ordering on indicator columns
# fzn_lex_lesseq_int([col_{v+1}], [col_v]) means col_{v+1} <=_lex col_v
lines.append("% Symmetry breaking: lex ordering on cluster indicator columns")
for v in range(1, K):
    # Column for cluster v+1 should be lex <= column for cluster v
    col_next = [f"iind_{v+1}_{i}" for i in range(1, N + 1)]
    col_curr = [f"iind_{v}_{i}" for i in range(1, N + 1)]
    lines.append(
        f"constraint fzn_lex_lesseq_int([{', '.join(col_next)}], [{', '.join(col_curr)}]);"
    )
lines.append("")

# Value precedence: first node in cluster 1 (WLOG)
lines.append("% Value precedence: first node is in cluster 1")
lines.append("constraint int_eq(c1, 1);")
lines.append("")

# Solve
lines.append("solve maximize obj;")
lines.append("")

# Write output
content = "\n".join(lines)
with open(OUTPUT, "w") as f:
    f.write(content)

total_lines = len(lines)
num_constraints = sum(1 for l in lines if l.startswith("constraint"))
print(f"Wrote {OUTPUT}")
print(f"  {total_lines} lines, {num_constraints} constraints")
print(f"  {N} nodes, {K} clusters, {len(edges)} edges")
print(f"  Objective range: 0..{total_weight}")
