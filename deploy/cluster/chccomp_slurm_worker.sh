#!/bin/bash
#SBATCH --job-name=ay-chccomp-worker
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=8
#SBATCH --mem=32G
#SBATCH --time=24:00:00
#SBATCH --array=0-10
#SBATCH --output=logs/ay-worker-%A_%a.out
#SBATCH --error=logs/ay-worker-%A_%a.err
# ay-script: chccomp-slurm-worker

