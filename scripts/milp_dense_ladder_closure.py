"""Close the two known dense-binary AY/Gurobi comparison gaps.

The corpus is generated by ``crates/ay-milp/examples/milp_speed.rs``.  This
harness freezes that already-built generator and the production ``ay-milp``
binary, asks the generator to dump deterministic MPS, then feeds those identical
bytes to both production AY and Gurobi under one serial `_oom_guard` lease.  It
does not build: benchmark/build overlap is a hard refusal.

Default cases are exactly the known open evidence:

* the twelve <=75x56 ladder members at matched 8T, covering the historical gap;
* the same twelve members at matched 1T, preventing a routed 8T win from hiding
  a new serial regression;
* 80x60 seed 2026, where Gurobi 1T proved in 102.02s and AY did not at 180s.

A case closes only when both solvers return the published optimum, both emitted
points pass production AY's exact rational checker against the shared MPS, and
AY's end-to-end process wall is no greater.  Timeouts, invalid optima, missing
output, memory-envelope breaches, and truncation all fail closed.

Exit status is zero only when every repetition of every case closes.  Any
measured Gurobi advantage or invalid/incomplete solver evidence returns one;
argument/preflight failures remain non-zero through ``argparse`` or an exception.
"""

