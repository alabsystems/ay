/// Repo-relative path of the public index (ships).
const PUBLIC_INDEX: &str = "scripts/index.toml";
/// Repo-relative path of the internal index (never ships).
const INTERNAL_INDEX: &str = "scripts/index-internal.toml";
/// Repo-relative path of the generated public catalog.
const README_PATH: &str = "scripts/README.md";
/// Repo-relative path of the publication allowlist manifest.
const MANIFEST_PATH: &str = "publish/manifest.txt";
/// Marker opening the generated exclusion block in the manifest.
const GENERATED_BEGIN: &str = "# BEGIN generated by ay scripts sync-manifest";
/// Marker closing the generated exclusion block in the manifest.
const GENERATED_END: &str = "# END generated";

