fn is_kebab(s: &str) -> bool {
    !s.is_empty()
        && !s.starts_with('-')
        && !s.ends_with('-')
        && !s.contains("--")
        && s.chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

impl ScriptEntry {
    fn validate(&self) -> Result<()> {
        if !is_kebab(&self.name) {
            bail!("name `{}` is not kebab-case", self.name);
        }
        if self.path.is_empty() || self.path.starts_with('/') || self.path.contains("..") {
            bail!("path `{}` must be repo-relative", self.path);
        }
        let mut segments = self.group.split('.');
        let root = segments.next().unwrap_or("");
        if !GROUP_ROOTS.contains(&root) {
            bail!(
                "group `{}`: first segment `{}` is not in the closed taxonomy ({})",
                self.group,
                root,
                GROUP_ROOTS.join("|")
            );
        }
        for seg in self.group.split('.') {
            if !is_kebab(seg) {
                bail!("group `{}`: bad segment `{}`", self.group, seg);
            }
        }
        if self.summary.is_empty() {
            bail!("summary must not be empty");
        }
        if self.entrypoint == Entrypoint::Cli && self.cli.is_empty() && self.cli_note.is_empty() {
            bail!("entrypoint=cli with cli=\"\" requires a cli_note explaining why no subcommand fronts it");
        }
        if !self.replaced_by.is_empty() && self.status != Status::Deprecated {
            bail!("replaced_by is set but status is not deprecated");
        }
        Ok(())
    }
}

impl Index {
    fn load(path: &Path, expected: Publish) -> Result<Self> {
        let body =
            fs::read_to_string(path).with_context(|| format!("read index {}", path.display()))?;
        let index: Index =
            toml::from_str(&body).with_context(|| format!("parse index {}", path.display()))?;
        if index.schema_version != 1 {
            bail!(
                "index {}: unsupported schema_version {} (expected 1)",
                path.display(),
                index.schema_version
            );
        }
        for entry in &index.scripts {
            entry
                .validate()
                .with_context(|| format!("script {} in {}", entry.name, path.display()))?;
            if entry.publish != expected {
                bail!(
                    "index {}: script {} has publish={} but this is the {} index",
                    path.display(),
                    entry.name,
                    entry.publish.label(),
                    expected.label()
                );
            }
        }
        Ok(index)
    }
}

/// Both index halves, loaded and cross-validated.
struct Loaded {
    public: Index,
    /// `None` in public snapshots, where the internal index never ships.
    internal: Option<Index>,
}

impl Loaded {
    fn load(root: &Path) -> Result<Self> {
        let public = Index::load(&root.join(PUBLIC_INDEX), Publish::Public)?;
        let internal_path = root.join(INTERNAL_INDEX);
        let internal = if internal_path.is_file() {
            Some(Index::load(&internal_path, Publish::Internal)?)
        } else {
            None
        };
        let loaded = Loaded { public, internal };
        validate_cross(&loaded.public, loaded.internal.as_ref())?;
        Ok(loaded)
    }

    fn entries(&self) -> impl Iterator<Item = &ScriptEntry> {
        self.public
            .scripts
            .iter()
            .chain(self.internal.iter().flat_map(|i| i.scripts.iter()))
    }

    fn find(&self, name: &str) -> Result<&ScriptEntry> {
        self.entries().find(|e| e.name == name).ok_or_else(|| {
            anyhow!("script `{name}` not found in the index (see `ay scripts list`)")
        })
    }
}

/// Cross-file invariants: names unique across both halves, `requires`
/// targets resolve.
fn validate_cross(public: &Index, internal: Option<&Index>) -> Result<()> {
    let mut names = BTreeSet::new();
    let mut paths = BTreeSet::new();
    let all: Vec<&ScriptEntry> = public
        .scripts
        .iter()
        .chain(internal.iter().flat_map(|i| i.scripts.iter()))
        .collect();
    for entry in &all {
        if !names.insert(entry.name.as_str()) {
            bail!(
                "duplicate script name `{}` across the index files",
                entry.name
            );
        }
        if !paths.insert(entry.path.as_str()) {
            bail!(
                "duplicate script path `{}` across the index files",
                entry.path
            );
        }
    }
    for entry in &all {
        for req in &entry.requires {
            if !names.contains(req.as_str()) {
                bail!(
                    "script {}: requires `{}` which has no index entry",
                    entry.name,
                    req
                );
            }
        }
    }
    Ok(())
}

