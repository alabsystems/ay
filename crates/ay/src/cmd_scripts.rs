/// Parse of the publication manifest as far as `scripts check` needs it.
struct PublishManifest {
    /// Allowlisted top-level names (dirs or files), the non-`!` lines.
    allow: Vec<String>,
    /// `!` exclusions outside the generated block, without the leading `!`.
    hand_exclusions: Vec<String>,
    /// Raw lines between the BEGIN/END markers (markers excluded).
    /// `None` when the markers are absent.
    generated: Option<Vec<String>>,
}

impl PublishManifest {
    fn parse(path: &Path) -> Result<Self> {
        let body = fs::read_to_string(path)
            .with_context(|| format!("read manifest {}", path.display()))?;
        let mut allow = Vec::new();
        let mut hand_exclusions = Vec::new();
        let mut generated: Option<Vec<String>> = None;
        let mut in_generated = false;
        for line in body.lines() {
            let trimmed = line.trim();
            if trimmed == GENERATED_BEGIN {
                if generated.is_some() {
                    bail!("{}: duplicate `{}` marker", path.display(), GENERATED_BEGIN);
                }
                generated = Some(Vec::new());
                in_generated = true;
                continue;
            }
            if trimmed == GENERATED_END {
                if !in_generated {
                    bail!(
                        "{}: `{}` marker without a BEGIN",
                        path.display(),
                        GENERATED_END
                    );
                }
                in_generated = false;
                continue;
            }
            if in_generated {
                generated
                    .as_mut()
                    .expect("in generated block")
                    .push(line.to_string());
                continue;
            }
            if trimmed.is_empty() || trimmed.starts_with('#') {
                continue;
            }
            if let Some(excl) = trimmed.strip_prefix('!') {
                hand_exclusions.push(excl.to_string());
            } else {
                allow.push(trimmed.to_string());
            }
        }
        if in_generated {
            bail!(
                "{}: unterminated `{}` block",
                path.display(),
                GENERATED_BEGIN
            );
        }
        Ok(PublishManifest {
            allow,
            hand_exclusions,
            generated,
        })
    }

    /// Every exclusion pattern, generated block included.
    fn all_exclusions(&self) -> Vec<String> {
        let mut all = self.hand_exclusions.clone();
        if let Some(generated) = &self.generated {
            for line in generated {
                if let Some(excl) = line.trim().strip_prefix('!') {
                    all.push(excl.to_string());
                }
            }
        }
        all
    }

    /// Is `path` under an allowlisted top-level entry?
    fn allowlisted(&self, path: &str) -> bool {
        let top = path.split('/').next().unwrap_or(path);
        self.allow.iter().any(|a| a == top || a == path)
    }

    fn excluded(&self, path: &str) -> bool {
        self.all_exclusions()
            .iter()
            .any(|e| pattern_covers(e, path))
    }
}

/// The exclusion block `sync-manifest` derives from the internal index:
/// the internal index itself, then one `!` line per internal entry whose
/// path sits under an allowlisted directory and is not already covered by a
/// hand-maintained exclusion. Order follows the internal index file.
fn expected_generated_block(
    internal: &[ScriptEntry],
    hand_exclusions: &[String],
    manifest: &PublishManifest,
) -> Vec<String> {
    let mut lines = vec![format!("!{INTERNAL_INDEX}")];
    for entry in internal {
        if !manifest.allowlisted(&entry.path) {
            continue; // non-allowlisted dirs (docs/, reports/, tools/) never ship
        }
        if hand_exclusions
            .iter()
            .any(|e| pattern_covers(e, &entry.path))
        {
            continue; // already covered outside the generated block
        }
        lines.push(format!("!{}", entry.path));
    }
    lines
}

