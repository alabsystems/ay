pub(crate) fn run(cmd: ScriptsCommand) -> Result<i32> {
    match cmd {
        ScriptsCommand::List(args) => run_list(args),
        ScriptsCommand::Show(args) => run_show(args),
        ScriptsCommand::Run(args) => run_run(args),
        ScriptsCommand::Check(args) => run_check(args),
        ScriptsCommand::Readme(args) => run_readme(args),
    }
}

fn run_list(args: ListArgs) -> Result<i32> {
    let loaded = Loaded::load(&repo_root()?)?;
    let group_matches = |group: &str| -> bool {
        match &args.group {
            None => true,
            Some(prefix) => group == prefix || group.starts_with(&format!("{prefix}.")),
        }
    };
    let entries: Vec<&ScriptEntry> = loaded
        .entries()
        .filter(|e| group_matches(&e.group))
        .filter(|e| args.publish.map_or(true, |p| e.publish == p))
        .filter(|e| args.status.map_or(true, |s| e.status == s))
        .filter(|e| {
            args.tool
                .as_ref()
                .map_or(true, |t| e.tools.iter().any(|x| x == t))
        })
        .collect();
    if args.json {
        println!("{}", serde_json::to_string_pretty(&entries)?);
        return Ok(0);
    }
    println!(
        "{:<28} {:<20} {:<7} {:<9} {:<11} {:<38} SUMMARY",
        "NAME", "GROUP", "LANG", "PUBLISH", "STATUS", "CLI"
    );
    for e in entries {
        let cli = if e.cli.is_empty() {
            "-"
        } else {
            e.cli.as_str()
        };
        println!(
            "{:<28} {:<20} {:<7} {:<9} {:<11} {:<38} {}",
            e.name,
            e.group,
            e.lang.label(),
            e.publish.label(),
            e.status.label(),
            cli,
            e.summary
        );
    }
    Ok(0)
}

