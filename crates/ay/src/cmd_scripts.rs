/// Walk up from the current directory to the checkout containing the index.
fn repo_root() -> Result<PathBuf> {
    let mut dir = env::current_dir().context("determine current directory")?;
    loop {
        if dir.join(PUBLIC_INDEX).is_file() {
            return Ok(dir);
        }
        if !dir.pop() {
            bail!("could not locate {PUBLIC_INDEX} above the current directory; run inside the ay repo");
        }
    }
}

/// Map of tracked path -> git mode string (e.g. "100755"), from
/// `git ls-files -s`.
fn git_tracked(root: &Path) -> Result<BTreeMap<String, String>> {
    let out = ProcCommand::new("git")
        .args(["ls-files", "-s", "-z"])
        .current_dir(root)
        .output()
        .context("run `git ls-files -s` (is git installed?)")?;
    if !out.status.success() {
        bail!(
            "`git ls-files` failed in {}: {}",
            root.display(),
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    let mut tracked = BTreeMap::new();
    for record in out.stdout.split(|&b| b == 0) {
        if record.is_empty() {
            continue;
        }
        let record = String::from_utf8_lossy(record);
        // Format: "<mode> <sha> <stage>\t<path>"
        let Some((meta, path)) = record.split_once('\t') else {
            continue;
        };
        let mode = meta.split(' ').next().unwrap_or("").to_string();
        tracked.insert(path.to_string(), mode);
    }
    Ok(tracked)
}

/// Env var name for a declared tool: uppercased, non-alphanumeric -> `_`.
fn tool_env_var(name: &str) -> String {
    let mangled: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    format!("AY_TOOL_{mangled}")
}

/// Resolve a declared tool: `$AY_TOOL_<NAME>` override first, then `$PATH`.
fn resolve_tool(name: &str) -> Option<PathBuf> {
    if let Some(over) = env::var_os(tool_env_var(name)) {
        let p = PathBuf::from(over);
        if p.is_file() {
            return Some(p);
        }
    }
    let path_var = env::var_os("PATH")?;
    for dir in env::split_paths(&path_var) {
        let candidate = dir.join(name);
        if candidate.is_file() {
            return Some(candidate);
        }
    }
    None
}

/// Simple glob: `*` matches any run of characters except `/`; patterns are
/// matched segment-wise and cover a path when they match a leading prefix of
/// its segments (so `proofs/evidence` covers `proofs/evidence/x/y.sh`).
fn pattern_covers(pattern: &str, path: &str) -> bool {
    let pat_segs: Vec<&str> = pattern.split('/').collect();
    let path_segs: Vec<&str> = path.split('/').collect();
    let mut pi = 0usize;
    for (i, pseg) in pat_segs.iter().enumerate() {
        if *pseg == "**" {
            // `**` swallows the rest of the path.
            return true;
        }
        match path_segs.get(i) {
            Some(sseg) if segment_match(pseg, sseg) => pi = i + 1,
            _ => return false,
        }
    }
    // All pattern segments matched a prefix of the path.
    pi == pat_segs.len()
}

/// Match one path segment against a pattern segment with `*` wildcards.
fn segment_match(pattern: &str, segment: &str) -> bool {
    // Iterative greedy glob restricted to one segment.
    let (p, s): (Vec<char>, Vec<char>) = (pattern.chars().collect(), segment.chars().collect());
    let (mut pi, mut si) = (0usize, 0usize);
    let (mut star, mut mark) = (None::<usize>, 0usize);
    while si < s.len() {
        if pi < p.len() && (p[pi] == s[si]) {
            pi += 1;
            si += 1;
        } else if pi < p.len() && p[pi] == '*' {
            star = Some(pi);
            mark = si;
            pi += 1;
        } else if let Some(sp) = star {
            pi = sp + 1;
            mark += 1;
            si = mark;
        } else {
            return false;
        }
    }
    while pi < p.len() && p[pi] == '*' {
        pi += 1;
    }
    pi == p.len()
}

