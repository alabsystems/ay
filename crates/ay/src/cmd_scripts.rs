//! `ay scripts` — discover, run, and gate the repo's indexed scripts.
//!
//! The registry is `scripts/index.toml` (public half) plus
//! `scripts/index-internal.toml` (internal half, `!`-excluded from
//! publish/manifest.txt and therefore present only in dev checkouts). Both
//! files share one schema (schema_version, `[[script]]` arrays); names are
//! unique across the pair and every entry validates on load, corpora.toml
//! style. The index is the source of truth; the CLI is a thin validated
//! reader/runner.
//!
//! 0.1.0 verbs: `list`, `show`, `run`, `check`, `readme`. The `check` verb
//! also carries the `sync-manifest` gate mode (diff-check of the generated
//! exclusion block in publish/manifest.txt); a `sync-manifest --write` verb
//! lands post-0.1.0 — the manifest is never auto-written.

