//! The module-qualified parameter names libz3 accepts, for CLI drop-in parity.
//!
//! z3 rejects a parameter only when the MODULE or the NAME is unknown
//! (`smt.bogus_knob=1` -> "unknown parameter", `bogusmodule.x=1` -> "unknown
//! module"); it accepts every real parameter, and is loose about values
//! (`smt.arith.solver=99` is accepted). Consumers pass these on every
//! invocation -- Why3, Dafny and Boogie all set `smt.mbqi` and friends.
//!
//! AY used to reject EVERY module-qualified parameter with a fatal error and no
//! verdict, so those consumers got an error where z3 solved. Now AY accepts the
//! same set z3 does. The tuning knobs AY does not implement are accepted and
//! IGNORED, with an honest note on stderr -- never silently. Ignoring a tuning
//! knob cannot change a verdict's soundness: it selects an internal strategy,
//! and AY's answers remain sound (at most, completeness differs from what z3
//! would do with the same knob honored).
//!
//! Parameters AY genuinely implements or translates are matched EARLIER in the
//! argv preprocessor, so they never reach this table.
//!
//! Garbage still fails loudly, exactly as z3 fails it -- that honest-rejection
//! property is deliberate and is what keeps a typo from being silently ignored.
//!
//! PROVENANCE: mechanically generated from libz3 5.0.0 via
//! `/opt/homebrew/bin/z3 -pm` and `/opt/homebrew/bin/z3 -pm:<module>`.
//! To regenerate against a newer z3, re-run that pair and rebuild this list;
//! do not hand-edit entries.

