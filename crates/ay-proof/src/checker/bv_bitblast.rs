/// Recognize whether `clause` is a strict-checkable (ungated) bit-blast lemma —
/// i.e. whether [`validate_bv_bitblast`] with no gate annotation would accept it.
///
/// This is the exact inverse of the validator's semantic checks: the
/// proof classifier (`ay-dpll`) calls it to upgrade a `Generic`/trust lemma into
/// the strict-checkable `BvBitBlast` kind ONLY when strict mode will
/// independently re-validate it by exhaustive evaluation or a checked
/// bit-blast/LRAT refutation — so classifier and checker cannot drift. A
/// non-tautological, unsupported, or too-wide clause is rejected.
#[must_use]
pub fn recognize_bv_bitblast(terms: &TermStore, clause: &[TermId]) -> bool {
    validate_bv_bitblast(terms, ProofId(0), clause, None).is_ok()
}

/// Maximum number of lemmas in one proof that may invoke the proof-producing
/// bit-blast/LRAT fallback.  The fallback has a finite per-lemma deadline; this
/// whole-proof cap prevents an untrusted proof from multiplying that deadline
/// by an arbitrary number of individually bounded lemmas.
pub const MAX_PROOF_PRODUCING_BV_LEMMAS_PER_PROOF: usize = 8;

/// Whether validating `clause` can require the proof-producing fallback.
///
/// This is a cheap structural classification only: clauses covered by the
/// exhaustive <=8-assignment-bit evaluator return `false`; wider or otherwise
/// unsupported bounded-evaluator shapes with BV content return `true`.  It does
/// not claim the clause is valid.
#[must_use]
pub fn bv_bitblast_requires_proof_producer(terms: &TermStore, clause: &[TermId]) -> bool {
    if !clause_mentions_bv(terms, clause) {
        return false;
    }
    match collect_bounded_vars(terms, clause) {
        Some(vars) => vars
            .iter()
            .try_fold(0_u32, |total, var| total.checked_add(var.bits))
            .is_none_or(|total| total > MAX_BOUNDED_ASSIGNMENT_BITS),
        None => true,
    }
}

/// Reject a strict proof whose tagged BV lemmas can multiply the bounded
/// proof-producing fallback beyond the whole-proof resource budget.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) struct ProofProducingBvAggregateCharge {
    pub(crate) work: usize,
    pub(crate) bytes: usize,
}

pub(crate) fn validate_proof_producing_bv_budget(
    proof: &Proof,
    terms: &TermStore,
) -> Result<ProofProducingBvAggregateCharge, ProofCheckError> {
    let mut count = 0_usize;
    for (index, step) in proof.steps.iter().enumerate() {
        let ProofStep::TheoryLemma { clause, kind, .. } = step else {
            continue;
        };
        if !matches!(
            kind,
            TheoryLemmaKind::BvBitBlast | TheoryLemmaKind::BvBitBlastGate { .. }
        ) || !bv_bitblast_requires_proof_producer(terms, clause)
        {
            continue;
        }
        count = count.checked_add(1).ok_or(ProofCheckError::ResourceLimit)?;
        if count > MAX_PROOF_PRODUCING_BV_LEMMAS_PER_PROOF {
            return Err(ProofCheckError::InvalidTheoryLemma {
                step: ProofId(index as u32),
                reason: format!(
                    "proof contains more than {MAX_PROOF_PRODUCING_BV_LEMMAS_PER_PROOF} lemmas \
                     requiring the bounded proof-producing BV checker"
                ),
            });
        }
    }
    let work_per_lemma = usize::try_from(PROOF_PRODUCING_AGGREGATE_WORK_PER_LEMMA)
        .map_err(|_| ProofCheckError::ResourceLimit)?;
    Ok(ProofProducingBvAggregateCharge {
        work: count
            .checked_mul(work_per_lemma)
            .ok_or(ProofCheckError::ResourceLimit)?,
        bytes: count
            .checked_mul(PROOF_PRODUCING_AGGREGATE_BYTES_PER_LEMMA)
            .ok_or(ProofCheckError::ResourceLimit)?,
    })
}

/// Recognize the deliberately narrow `evaluate` fragment used to certify a
/// preprocessing-folded bitvector concat: one unit equality from a closed
/// concat tree to its exact BV constant, with total width at most 64 bits.
///
/// Keeping this separate from [`recognize_bv_bitblast`] avoids widening that
/// rule's bounded symbolic truth-table surface merely to check one closed
/// constant-folding fact.
#[must_use]
pub fn recognize_bv_ground_evaluate(terms: &TermStore, clause: &[TermId]) -> bool {
    validate_bv_ground_evaluate(terms, ProofId(0), clause, 0, &[]).is_ok()
}

/// Strictly validate the Carcara `evaluate` shape emitted for folded BV
/// concats. This is intentionally not a general evaluator: no variables,
/// non-concat operators, premises, arguments, or widths above 64 are admitted.
pub(crate) fn validate_bv_ground_evaluate(
    terms: &TermStore,
    step_id: ProofId,
    clause: &[TermId],
    premise_count: usize,
    args: &[TermId],
) -> Result<(), ProofCheckError> {
    let invalid = |reason: &str| ProofCheckError::InvalidTheoryLemma {
        step: step_id,
        reason: format!("evaluate: {reason}"),
    };
    if premise_count != 0 {
        return Err(invalid("ground BV evaluation must not have premises"));
    }
    if !args.is_empty() {
        return Err(invalid("ground BV evaluation must not have arguments"));
    }
    let [equality] = clause else {
        return Err(invalid(
            "ground BV evaluation must conclude one equality literal",
        ));
    };
    if terms.sort(*equality) != &Sort::Bool {
        return Err(invalid("conclusion equality must have Bool sort"));
    }
    let TermData::App(Symbol::Named(name), equality_args) = terms.get(*equality) else {
        return Err(invalid("conclusion must be an equality application"));
    };
    if name != "=" || equality_args.len() != 2 {
        return Err(invalid("conclusion must be a binary equality"));
    }

    let (actual, actual_width, contains_concat) = eval_ground_concat(terms, equality_args[0], 0)
        .ok_or_else(|| invalid("left side is not a well-sorted closed concat tree"))?;
    if !contains_concat {
        return Err(invalid("left side must contain a concat"));
    }
    let (expected, expected_width) = eval_ground_bv_constant(terms, equality_args[1])
        .ok_or_else(|| invalid("right side must be a well-sorted BV constant"))?;
    if actual_width != expected_width || actual != expected {
        return Err(invalid(
            "closed concat does not evaluate to the asserted BV constant",
        ));
    }
    Ok(())
}

fn eval_ground_concat(terms: &TermStore, term: TermId, depth: u32) -> Option<(u64, u32, bool)> {
    if depth > 512 {
        return None;
    }
    if let Some((value, width)) = eval_ground_bv_constant(terms, term) {
        return Some((value, width, false));
    }
    let TermData::App(Symbol::Named(name), concat_args) = terms.get(term) else {
        return None;
    };
    if name != "concat" || concat_args.len() != 2 {
        return None;
    }
    let (high, high_width, _) = eval_ground_concat(terms, concat_args[0], depth + 1)?;
    let (low, low_width, _) = eval_ground_concat(terms, concat_args[1], depth + 1)?;
    let width = high_width.checked_add(low_width)?;
    if high_width == 0 || low_width == 0 || width > u64::BITS || low_width >= u64::BITS {
        return None;
    }
    if terms.sort(term) != &Sort::bitvec(width) {
        return None;
    }
    Some(((high << low_width) | low, width, true))
}

fn eval_ground_bv_constant(terms: &TermStore, term: TermId) -> Option<(u64, u32)> {
    let TermData::Const(Constant::BitVec { value, width }) = terms.get(term) else {
        return None;
    };
    if *width == 0 || *width > u64::BITS || terms.sort(term) != &Sort::bitvec(*width) {
        return None;
    }
    let value = value.to_u64()?;
    if value > bv_mask(*width) {
        return None;
    }
    Some((value, *width))
}

/// Recognize whether `clause` is a strict-checkable Boolean tautology — every
/// literal is `Bool`-sorted and the clause is TRUE under every assignment of its
/// bounded (Bool / small-BV) variables. The exact inverse of
/// [`validate_bool_tautology`].
#[must_use]
pub fn recognize_bool_tautology(terms: &TermStore, clause: &[TermId]) -> bool {
    validate_bool_tautology(terms, ProofId(0), clause).is_ok()
}

/// Validate a `BoolTautology` lemma in strict mode: a propositional/Boolean
/// equality or formula that is TRUE under every assignment of its bounded
/// variables (e.g. `(= (not (not p)) p)`, `(= (and p p) p)`). Reuses the same
/// exhaustive bounded evaluator as the bit-blast path, but WITHOUT the
/// `clause_mentions_bv` content requirement — a pure-Boolean tautology has no
/// bitvector sub-term, and the exhaustive evaluation IS the soundness check
/// (every assignment satisfies the clause), so no BV content is needed. Every
/// literal must be `Bool`-sorted, and all variables must be bounded (else the
/// checker cannot exhaustively evaluate and fails closed).
pub(crate) fn validate_bool_tautology(
    terms: &TermStore,
    step_id: ProofId,
    clause: &[TermId],
) -> Result<(), ProofCheckError> {
    if clause.is_empty() {
        return Err(ProofCheckError::InvalidTheoryLemma {
            step: step_id,
            reason: "bool tautology clause must be non-empty".to_string(),
        });
    }
    for &lit in clause {
        if !matches!(terms.sort(lit), Sort::Bool) {
            return Err(ProofCheckError::InvalidTheoryLemma {
                step: step_id,
                reason: format!(
                    "bool tautology literal has non-Bool sort {:?}; the clause must \
                     be purely propositional",
                    terms.sort(lit)
                ),
            });
        }
    }
    // Packed clausification units can contain theory atoms the bounded
    // Bool/BV evaluator intentionally cannot interpret. Their propositional
    // tautology is nevertheless decidable by exact structure:
    //
    //   (or p (not p))
    //   (or child (not (and ... child ...)))
    //   (or p q ... (not (or p q ...)))
    //
    // The conjunction form is packed Alethe `and_pos`; top-level assertion
    // flattening also generates the OR/self-complement unit. Recognize only a
    // literal and its exact complement, an exact child of the negated
    // conjunction, or every member of the negated disjunction. The atoms'
    // theory semantics are irrelevant, so this remains sound for RM, arrays,
    // datatypes, and every other Boolean-sorted atom.
    if let [unit] = clause {
        if is_packed_clausification_tautology(terms, *unit) {
            return Ok(());
        }
    }
    validate_bounded_clause_semantics(terms, step_id, clause)
}

fn is_packed_clausification_tautology(terms: &TermStore, term: TermId) -> bool {
    let TermData::App(symbol, disjuncts) = terms.get(term) else {
        return false;
    };
    if symbol.name() != "or" || disjuncts.len() < 2 {
        return false;
    }
    if disjuncts
        .iter()
        .any(|&disjunct| terms.sort(disjunct) != &Sort::Bool)
    {
        return false;
    }
    for &negated in disjuncts {
        let TermData::Not(inner) = terms.get(negated) else {
            continue;
        };
        if terms.sort(*inner) != &Sort::Bool {
            continue;
        }
        if disjuncts.contains(inner) {
            return true;
        }
        let TermData::App(join_symbol, members) = terms.get(*inner) else {
            continue;
        };
        if members
            .iter()
            .any(|&member| terms.sort(member) != &Sort::Bool)
        {
            continue;
        }
        match join_symbol.name() {
            "and"
                if disjuncts
                    .iter()
                    .any(|other| *other != negated && members.contains(other)) =>
            {
                return true;
            }
            "or" if !members.is_empty()
                && members.iter().all(|member| {
                    disjuncts
                        .iter()
                        .any(|other| *other != negated && other == member)
                }) =>
            {
                return true;
            }
            _ => {}
        }
    }
    // The two DUAL shapes, where the gate term occurs POSITIVELY in the packed
    // unit — Alethe `and_neg` and `or_neg`:
    //
    //   (or (and t1 .. tn) (not t1) .. (not tn))   -- and_neg
    //   (or (or  t1 .. tn) (not ti))               -- or_neg
    //
    // Tautology by the same one-line case split as the negated shapes above.
    // `and_neg`: either every `ti` holds, so the conjunction disjunct is true,
    // or some `ti` fails, and ITS negation is one of the disjuncts. `or_neg`:
    // either `ti` holds, so the disjunction disjunct is true, or it fails and
    // `(not ti)` is a disjunct. Both are exact — the members' theory semantics
    // are irrelevant, exactly as for `and_pos`/`or_pos`.
    //
    // Without `and_neg` the Tseitin definition clause of a top-level `(and ..)`
    // over non-Bool-bounded atoms (e.g. an EUF equality) reached the strict
    // checker as a bare `assume` and a correct QF_UF refutation under
    // `:produce-unsat-cores` was rejected as "assumes term outside the supplied
    // problem obligation", publishing `unknown` where z3 says `unsat`
    // (#uc-and-neg-packed-tautology).
    for &positive in disjuncts {
        let TermData::App(join_symbol, members) = terms.get(positive) else {
            continue;
        };
        if members.is_empty() || members.iter().any(|&m| terms.sort(m) != &Sort::Bool) {
            continue;
        }
        let negation_present = |member: TermId| {
            disjuncts.iter().any(|&other| {
                other != positive
                    && matches!(terms.get(other), TermData::Not(inner) if *inner == member)
            })
        };
        match join_symbol.name() {
            "and" if members.iter().all(|&m| negation_present(m)) => return true,
            "or" if members.iter().any(|&m| negation_present(m)) => return true,
            _ => {}
        }
    }
    false
}

/// Validate a `BvBitBlast` or `BvBitBlastGate` lemma in strict mode.
///
/// See module docs for the schema the clause must match.
pub(crate) fn validate_bv_bitblast(
    terms: &TermStore,
    step_id: ProofId,
    clause: &[TermId],
    gate: Option<(BvGateType, u32)>,
) -> Result<(), ProofCheckError> {
    if clause.is_empty() {
        return Err(ProofCheckError::InvalidTheoryLemma {
            step: step_id,
            reason: "bv_bitblast clause must be non-empty".to_string(),
        });
    }

    for &lit in clause {
        // Every literal in a propositional bit-blast clause must be Boolean-
        // sorted. If we see a BV/Int/Real literal directly, the prover is
        // trying to sneak a non-propositional term through the SAT interface.
        let lit_sort = terms.sort(lit);
        if !matches!(lit_sort, Sort::Bool) {
            return Err(ProofCheckError::InvalidTheoryLemma {
                step: step_id,
                reason: format!(
                    "bv_bitblast literal has non-Bool sort {lit_sort:?}; \
                     bit-blast clauses must be purely propositional"
                ),
            });
        }
    }

    // The clause must mention at least one sub-term that is actually a
    // bitvector thing: a BV constant, BV variable, BV gate output, or an
    // equality/comparison between BV terms. A clause with no BV content at
    // all is not a bit-blast product, so we reject it as a forgery.
    if !clause_mentions_bv(terms, clause) {
        return Err(ProofCheckError::InvalidTheoryLemma {
            step: step_id,
            reason: "bv_bitblast clause does not mention any bitvector \
                     sub-term; a forged lemma cannot hide behind this rule"
                .to_string(),
        });
    }

    // For the annotated gate form, require at least one sub-term that is an
    // application of an SMT-LIB operator consistent with the declared gate
    // type. This is a lightweight sanity check; it rejects lemmas whose
    // declared `gate_type = bvand` is incompatible with a clause that talks
    // only about `bvor`, etc.
    if let Some((gate_type, width)) = gate {
        let required_op = required_op_name(gate_type);
        // `None` means the gate type corresponds to a primitive shape
        // (const / variable / ite) rather than a concrete SMT-LIB operator.
        // For those we skip the operator check — the generic `clause_mentions_bv`
        // check above already rejects clauses without BV content.
        if let Some(op) = required_op {
            if !clause_mentions_matching_gate(terms, clause, op, gate_type, width) {
                return Err(ProofCheckError::InvalidTheoryLemma {
                    step: step_id,
                    reason: format!(
                        "bv_bitblast annotated gate {gate_type:?} requires \
                         the clause to reference operator `{op}` at width \
                         {width}, but no such sub-term was found"
                    ),
                });
            }
        }
    }

    validate_bv_bitblast_semantics(terms, step_id, clause)
}

/// The SEMANTIC half of `bv_bitblast` validation — exhaustive bounded
/// evaluation, falling back to the bounded bit-blast + LRAT proof producer and
/// its replay — memoized per `(store, clause)`.
///
/// PERF. Proof finalization runs `check_proof_strict*` as an atomic revert gate
/// after each of ~30 individual surgery passes, so ONE promoted `BvBitBlast`
/// lemma is re-decided many times per solve, on an unchanged clause in an
/// unchanged store. MEASURED at b0a836719b over the 28 `shl_is_mul_by_pow2`
/// queries: 226 entries into this decision procedure for 28 distinct decisions
/// — every query decides exactly ONE clause, 20 of them 12 times over — and
/// 41.3 s of the 53.2 s spent here is re-decision of a clause already accepted.
///
/// Nothing is checked less:
/// * the structural schema checks in [`validate_bv_bitblast`] (Boolean sorts,
///   BV content, gate-annotation agreement) run on EVERY call and are never
///   memoized — which is also why the memo key needs no gate annotation;
/// * only a COMPLETED, ACCEPTING decision is recorded, keyed by the exact
///   clause it was computed for. An acceptance from either checker is the
///   store-and-clause-determined semantic fact "this clause holds under every
///   assignment", so repeating it cannot change the answer;
/// * failures are never recorded — the proof-producing checker is
///   deadline-bounded, so a failure is a fact about one attempt rather than
///   about the clause, and a rejected lemma is re-decided every time exactly as
///   before;
/// * `TermStore` clears the memo on both operations that can change what a
///   `TermId` means (`rollback_to`, `mark_and_compact`), the only two writers
///   of its term arena after construction — every other mutation appends;
/// * the whole-proof [`MAX_PROOF_PRODUCING_BV_LEMMAS_PER_PROOF`] budget is a
///   structural count over the proof's steps, so it is unaffected.
fn validate_bv_bitblast_semantics(
    terms: &TermStore,
    step_id: ProofId,
    clause: &[TermId],
) -> Result<(), ProofCheckError> {
    if terms.strict_bv_semantics_validated(clause) {
        return Ok(());
    }
    match validate_bounded_clause_semantics(terms, step_id, clause) {
        Ok(()) => {
            terms.record_strict_bv_semantics_validated(clause);
            Ok(())
        }
        Err(bounded_error) => {
            match validate_proof_producing_clause_semantics(terms, step_id, clause) {
                Ok(()) => {
                    terms.record_strict_bv_semantics_validated(clause);
                    Ok(())
                }
                Err(proof_error) => Err(ProofCheckError::InvalidTheoryLemma {
                    step: step_id,
                    reason: format!(
                        "bv_bitblast semantic checks failed: bounded checker: {bounded_error}; \
                     proof-producing checker: {proof_error}"
                    ),
                }),
            }
        }
    }
}

/// Return the SMT-LIB operator name that must appear somewhere in the clause
/// for the given gate type. Returns `None` for gate types whose encoding
/// does not produce a named SMT-LIB operator (e.g., `Const`, `Variable`,
/// `Ite`).
fn required_op_name(gate_type: BvGateType) -> Option<&'static str> {
    match gate_type {
        BvGateType::And => Some("bvand"),
        BvGateType::Or => Some("bvor"),
        BvGateType::Xor => Some("bvxor"),
        BvGateType::Not => Some("bvnot"),
        BvGateType::Add => Some("bvadd"),
        BvGateType::Mul => Some("bvmul"),
        BvGateType::Neg => Some("bvneg"),
        BvGateType::Shl => Some("bvshl"),
        BvGateType::Lshr => Some("bvlshr"),
        BvGateType::Ashr => Some("bvashr"),
        BvGateType::Ult => Some("bvult"),
        BvGateType::Concat => Some("concat"),
        BvGateType::Extract => Some("extract"),
        BvGateType::ZeroExtend => Some("zero_extend"),
        BvGateType::SignExtend => Some("sign_extend"),
        BvGateType::Udiv => Some("bvudiv"),
        BvGateType::Urem => Some("bvurem"),
        // Primitive gates: no specific operator symbol required. Generic
        // BV-content check covers these. Any future `BvGateType` variants
        // default to "no specific operator" so we never crash on enum
        // extension.
        BvGateType::Eq | BvGateType::Const | BvGateType::Variable | BvGateType::Ite => None,
        _ => None,
    }
}

/// Return true if any literal in the clause contains (directly or nested) a
/// bitvector constant, bitvector variable, or bitvector-producing term.
fn clause_mentions_bv(terms: &TermStore, clause: &[TermId]) -> bool {
    let mut visited = HashSet::new();
    let mut pending = clause.to_vec();
    while let Some(term) = pending.pop() {
        if !visited.insert(term) {
            continue;
        }
        if matches!(terms.sort(term), Sort::BitVec(_)) {
            return true;
        }
        match terms.get(term) {
            TermData::App(_, args) => pending.extend(args.iter().copied()),
            TermData::Let(bindings, body) => {
                pending.extend(bindings.iter().map(|(_, value)| *value));
                pending.push(*body);
            }
            TermData::Not(inner) => pending.push(*inner),
            TermData::Ite(condition, then_branch, else_branch) => {
                pending.extend([*condition, *then_branch, *else_branch]);
            }
            TermData::Forall(_, body, triggers) | TermData::Exists(_, body, triggers) => {
                pending.push(*body);
                pending.extend(triggers.iter().flatten().copied());
            }
            _ => {}
        }
    }
    false
}

/// Return true if any literal in the clause contains an application matching
/// the annotated SMT-LIB operator somewhere in its sub-term tree.
fn clause_mentions_matching_gate(
    terms: &TermStore,
    clause: &[TermId],
    op: &str,
    gate_type: BvGateType,
    width: u32,
) -> bool {
    clause
        .iter()
        .any(|&lit| term_mentions_matching_gate(terms, lit, op, gate_type, width, &mut Vec::new()))
}

fn term_mentions_matching_gate(
    terms: &TermStore,
    term: TermId,
    op: &str,
    gate_type: BvGateType,
    width: u32,
    stack: &mut Vec<TermId>,
) -> bool {
    if stack.len() > 512 {
        return false;
    }
    stack.push(term);
    let result = match terms.get(term) {
        TermData::App(sym, args) => {
            (sym.name() == op && gate_width_matches(terms, term, args, gate_type, width))
                || args
                    .iter()
                    .any(|&a| term_mentions_matching_gate(terms, a, op, gate_type, width, stack))
        }
        TermData::Not(inner) => {
            term_mentions_matching_gate(terms, *inner, op, gate_type, width, stack)
        }
        TermData::Ite(c, t, e) => {
            term_mentions_matching_gate(terms, *c, op, gate_type, width, stack)
                || term_mentions_matching_gate(terms, *t, op, gate_type, width, stack)
                || term_mentions_matching_gate(terms, *e, op, gate_type, width, stack)
        }
        _ => false,
    };
    stack.pop();
    result
}

fn gate_width_matches(
    terms: &TermStore,
    term: TermId,
    args: &[TermId],
    gate_type: BvGateType,
    width: u32,
) -> bool {
    if !same_width_gate_requires_width_check(gate_type) {
        return true;
    }

    bitvec_width(terms.sort(term)) == Some(width)
        && !args.is_empty()
        && args
            .iter()
            .all(|&arg| bitvec_width(terms.sort(arg)) == Some(width))
}

fn same_width_gate_requires_width_check(gate_type: BvGateType) -> bool {
    matches!(
        gate_type,
        BvGateType::And
            | BvGateType::Or
            | BvGateType::Xor
            | BvGateType::Not
            | BvGateType::Add
            | BvGateType::Mul
            | BvGateType::Neg
            | BvGateType::Shl
            | BvGateType::Lshr
            | BvGateType::Ashr
            | BvGateType::Udiv
            | BvGateType::Urem
    )
}

fn bitvec_width(sort: &Sort) -> Option<u32> {
    match sort {
        Sort::BitVec(bv) => Some(bv.width),
        _ => None,
    }
}

