/// Source-bound evidence that one exact ordered Bool/BV query, optionally with
/// exact finite arrays or the narrow same-array read-congruence extension, is
/// unsatisfiable.
///
/// The constructor is private.  Evidence is issued only after the query has
/// been lowered from the live [`TermStore`], bit-blasted into provenance-bearing
/// CNF, refuted by the SAT engine, and independently replayed as a
/// [`crate::BvBlastProof`].  The opaque term-store stamp prevents a proof about
/// one arena snapshot from being retargeted after append, rollback, compaction,
/// clone, or wholesale replacement.
#[derive(Debug)]
pub struct AuthenticatedBoolBvUnsatQuery {
    term_snapshot: TermStoreSnapshotStamp,
    roots: Box<[TermId]>,
    used_exact_finite_arrays: bool,
    used_uninterpreted_leaves: bool,
}

impl AuthenticatedBoolBvUnsatQuery {
    /// Whether this evidence still denotes the same immutable term snapshot
    /// and exact ordered query roots.
    #[must_use]
    pub fn is_current_for(&self, terms: &TermStore, roots: &[TermId]) -> bool {
        self.term_snapshot == terms.snapshot_stamp() && self.roots.as_ref() == roots
    }

    /// Whether the immutable term snapshot authenticated by this evidence is
    /// still current.  Callers that seal the exact roots in a separate affine
    /// query-scope capability may use this narrower check at final consumption.
    #[must_use]
    pub fn term_snapshot_is_current(&self, terms: &TermStore) -> bool {
        self.term_snapshot == terms.snapshot_stamp()
    }

    /// Whether exact, full-domain finite-array scalarization contributed to
    /// this authentication.
    ///
    /// This flag is deliberately false for the separate same-array
    /// read-congruence weakening. It becomes true only when the source lowerer
    /// successfully handles at least one supported array sort or operator.
    #[must_use]
    pub fn used_exact_finite_arrays(&self) -> bool {
        self.used_exact_finite_arrays
    }

    /// Whether the congruence-free uninterpreted-application leaf abstraction
    /// contributed to this authentication (#bitblast-original-clause-authority).
    ///
    /// Only [`authenticate_uf_leaf_bool_bv_unsat_query`] can set this.  The
    /// abstraction maps each ground uninterpreted application to one free leaf
    /// keyed by its canonical term identity, which over-approximates the model
    /// class: a refutation of the abstraction refutes the exact query, so the
    /// minted capability's UNSAT claim is unchanged.  A SATISFIABLE abstraction
    /// says nothing about the exact query and never mints or vetoes anything.
    #[must_use]
    pub fn used_uninterpreted_leaves(&self) -> bool {
        self.used_uninterpreted_leaves
    }
}

/// Fail-closed reason why a source Bool/BV query could not be authenticated as
/// UNSAT.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum BoolBvUnsatAuthenticationError {
    /// The empty conjunction is satisfiable and cannot have an UNSAT proof.
    #[error("the Bool/BV query has no roots")]
    EmptyQuery,
    /// A supplied root does not name a term in the live store.
    #[error("query root {root} is outside the live term store")]
    InvalidRoot {
        /// The first invalid source root.
        root: TermId,
    },
    /// The query uses a sort or operator outside the checked Bool/BV fragment.
    #[error("query is outside the proof-producing Bool/BV fragment: {reason}")]
    UnsupportedFragment {
        /// Stable diagnostic from source lowering.
        reason: String,
    },
    /// The independently bit-blasted query is satisfiable, so no UNSAT
    /// capability may be minted.
    #[error("the independently bit-blasted Bool/BV query is satisfiable")]
    Satisfiable,
    /// Bounded proof production failed or exhausted its explicit envelope.
    #[error("Bool/BV refutation production failed: {reason}")]
    Refutation {
        /// Proof-production or bounded-resource diagnostic.
        reason: String,
    },
    /// The surfaced gate/resolution proof failed independent replay.
    #[error("Bool/BV refutation replay failed: {reason}")]
    Replay {
        /// Independent replay diagnostic.
        reason: String,
    },
    /// A deterministic bound or the caller deadline was exhausted before this
    /// lane could decide the query. Carries NO semantic information about the
    /// claimed refutation.
    #[error("Bool/BV authentication exhausted a bounded resource: {reason}")]
    ResourceLimit {
        /// Exhausted bounded resource diagnostic.
        reason: String,
    },
}

impl BoolBvUnsatAuthenticationError {
    /// Whether a different, independently checked theory-specific lane may be
    /// attempted because this checker simply does not implement the query's
    /// source fragment.
    #[must_use]
    pub fn is_unsupported_fragment(&self) -> bool {
        matches!(self, Self::UnsupportedFragment { .. })
    }

    /// Whether this error means "this lane cannot answer", as opposed to "the
    /// claimed refutation is wrong".
    ///
    /// This lane is an ADDITIONAL independent authenticator, not a gate: it
    /// runs after the Alethe presentation has already failed, and a lane that
    /// merely ran out of its own bounded envelope must DECLINE so the remaining
    /// certification routes -- in particular
    /// `discharge_trust_steps_for_certification` -- still get to run. Vetoing
    /// on budget exhaustion discards refutations this checker never examined.
    ///
    /// [`Self::Satisfiable`] and [`Self::Replay`] are deliberately EXCLUDED:
    /// they are positive evidence that the claimed UNSAT is wrong, and must
    /// keep failing closed.
    #[must_use]
    pub fn is_capability_decline(&self) -> bool {
        matches!(
            self,
            Self::UnsupportedFragment { .. } | Self::ResourceLimit { .. }
        )
    }
}

/// Allocation ceiling used by the independent replay validator alone.
const PROOF_PRODUCING_REPLAY_BYTES_PER_LEMMA: usize = 128 * 1024 * 1024;

// Replay is only one phase of the larger admission charge published above.
// Keeping its own tighter allocation limit prevents that outer accounting
// value from silently widening allocations inside the independent validator.

/// The source-bound checker may lower 128-bit terms inside an outer one-bit
/// Boolean refutation. Public/serialized top-level BV proofs remain capped by
/// `bv_blast_export::MAX_WIDTH`.
pub(super) const MAX_PROOF_PRODUCING_INTERNAL_BV_WIDTH: u32 = 128;

#[derive(Clone)]
enum ProofProducingExpr {
    Bool(BvExpr),
    BitVec(BvExpr, u32),
    Array(array_finite::FiniteArrayExpr),
}

fn balanced_bool_expr(
    mut expressions: Vec<BvExpr>,
    identity: bool,
    combine: fn(BvExpr, BvExpr) -> BvExpr,
) -> Result<BvExpr, String> {
    if expressions.is_empty() {
        return Ok(BvExpr::const_val(u128::from(identity), 1));
    }
    while expressions.len() > 1 {
        let mut next = Vec::new();
        next.try_reserve(expressions.len().div_ceil(2))
            .map_err(|error| format!("balanced Bool expression allocation failed: {error}"))?;
        let mut current = expressions.into_iter();
        while let Some(lhs) = current.next() {
            next.push(match current.next() {
                Some(rhs) => combine(lhs, rhs),
                None => lhs,
            });
        }
        expressions = next;
    }
    Ok(expressions.pop().expect("non-empty checked above"))
}

fn proof_producing_expr_nodes(expr: &ProofProducingExpr) -> Result<usize, String> {
    let roots: &[BvExpr] = match expr {
        ProofProducingExpr::Bool(expr) | ProofProducingExpr::BitVec(expr, _) => {
            std::slice::from_ref(expr)
        }
        ProofProducingExpr::Array(array) => &array.cells,
    };
    let mut stack = Vec::new();
    stack
        .try_reserve_exact(MAX_PROOF_PRODUCING_EXPR_DEPTH + 1)
        .map_err(|error| format!("BvExpr traversal allocation failed: {error}"))?;
    let mut nodes = 0_usize;
    for root in roots {
        nodes = bv_expr_nodes_from(root, nodes, &mut stack)?;
    }
    Ok(nodes)
}

fn bv_expr_nodes(expr: &BvExpr) -> Result<usize, String> {
    let mut stack = Vec::new();
    stack
        .try_reserve_exact(MAX_PROOF_PRODUCING_EXPR_DEPTH + 1)
        .map_err(|error| format!("BvExpr traversal allocation failed: {error}"))?;
    bv_expr_nodes_from(expr, 0, &mut stack)
}

fn bv_expr_nodes_from<'a>(
    root: &'a BvExpr,
    mut nodes: usize,
    stack: &mut Vec<(&'a BvExpr, usize)>,
) -> Result<usize, String> {
    stack.push((root, 1_usize));
    while let Some((expr, depth)) = stack.pop() {
        if depth > MAX_PROOF_PRODUCING_EXPR_DEPTH {
            return Err(format!(
                "lowered BvExpr exceeds {MAX_PROOF_PRODUCING_EXPR_DEPTH} depth"
            ));
        }
        nodes += 1;
        if nodes > MAX_PROOF_PRODUCING_EXPR_NODES {
            return Err(format!(
                "lowered BvExpr exceeds {MAX_PROOF_PRODUCING_EXPR_NODES} nodes"
            ));
        }
        match expr {
            BvExpr::Leaf { .. } | BvExpr::Const { .. } => {}
            BvExpr::ZeroExt(inner, _)
            | BvExpr::Extract { inner, .. }
            | BvExpr::SignExt(inner, _)
            | BvExpr::Not(inner) => stack.push((inner, depth + 1)),
            BvExpr::CarryOut { lhs, rhs, .. }
            | BvExpr::Add(lhs, rhs)
            | BvExpr::Sub(lhs, rhs)
            | BvExpr::Or(lhs, rhs)
            | BvExpr::And(lhs, rhs)
            | BvExpr::Xor(lhs, rhs)
            | BvExpr::Shl(lhs, rhs)
            | BvExpr::Lshr(lhs, rhs)
            | BvExpr::Ashr(lhs, rhs)
            | BvExpr::Eq(lhs, rhs)
            | BvExpr::Mul(lhs, rhs) => {
                stack.push((rhs, depth + 1));
                stack.push((lhs, depth + 1));
            }
        }
    }
    Ok(nodes)
}

/// Prove a symbolic Bool/BV clause by bit-blasting it to CNF, asking the SAT
/// engine for an LRAT-derived resolution DAG, and replaying the resulting
/// [`crate::BvBlastProof`]. This is the scalable complement to exhaustive
/// assignment enumeration: no solver verdict is accepted without the surfaced
/// gate provenance and resolution refutation validating end to end.
///
/// SOURCE BINDING. This strict-checker path accepts no serialized
/// `BvBlastProof`. It lowers the exact live `TermStore` clause into `BvExpr`,
/// constructs the graph from that expression, and bounded-replays the freshly
/// returned object in this same call. Thus there is no artifact-substitution
/// boundary at which `asserted_smt` or `obligation` metadata could replace the
/// checked clause. External stored-proof consumers must instead re-derive and
/// compare the graph before granting authority; `BvBlastProof::validate` alone
/// is deliberately only an internal graph/CNF replay.
fn validate_proof_producing_clause_semantics(
    terms: &TermStore,
    _step_id: ProofId,
    clause: &[TermId],
) -> Result<(), String> {
    if clause.is_empty() || clause.len() > MAX_PROOF_PRODUCING_CLAUSE_LITERALS {
        return Err(format!(
            "clause has {} literals (supported: 1..={MAX_PROOF_PRODUCING_CLAUSE_LITERALS})",
            clause.len()
        ));
    }

    let (limits, deadline) = proof_producing_limits(None);
    let mut lowerer = ProofProducingLowerer::new(terms, deadline);
    let lowered = lowerer.lower_bool_terms(clause)?;
    let disjunction = balanced_bool_expr(lowered, false, BvExpr::or)?;
    drop(lowerer);
    let truth = BvExpr::const_val(1, 1);
    let proof = export_bv_blast_proof_expr_with_limits(&disjunction, &truth, &limits)
        .map_err(|error| format!("negated clause did not yield a refutation: {error}"))?;
    let replay_limits = proof_replay_limits(&limits);
    proof
        .validate_with_limits(&replay_limits)
        .map_err(|error| format!("surfaced bit-blast refutation failed replay: {error}"))?;
    Ok(())
}

fn proof_replay_limits(limits: &BvExprProofLimits) -> BvBlastValidateLimits {
    BvBlastValidateLimits {
        deadline: limits
            .resolution
            .validation
            .deadline
            .or(limits.resolution.deadline),
        max_vars: limits.resolution.max_num_vars,
        max_bit_lemmas: limits.max_estimated_gate_work,
        max_clauses: limits.resolution.max_input_clauses,
        max_clause_literals: limits.resolution.max_input_clause_literals,
        max_original_literals: limits.resolution.max_input_literals,
        max_resolution_steps: limits.max_resolution_steps,
        max_derived_literals: limits.resolution.max_derived_literals,
        max_work: limits.resolution.validation.max_work,
    }
}

fn proof_producing_limits(caller_deadline: Option<Instant>) -> (BvExprProofLimits, Instant) {
    let local_deadline = Instant::now() + PROOF_PRODUCING_DEADLINE;
    let deadline = caller_deadline.map_or(local_deadline, |outer| outer.min(local_deadline));
    let mut resolution = ResolutionProofLimits {
        deadline: Some(deadline),
        // Keep the pre-upstream size trio. ay-sat documents about 849 resident
        // bytes per variable at construction before clauses; 600k variables
        // alone would exceed 480 MiB before the other separately bounded
        // phases. The clause-db threshold below explicitly is not a solver-wide
        // memory cap, so the larger trio cannot be admitted under the published
        // 768 MiB precharge without bounded/fallible SAT construction or an
        // enforced process RSS envelope.
        max_num_vars: 150_000,
        max_input_clauses: 700_000,
        max_input_literals: 3_000_000,
        max_input_clause_literals: 64,
        max_input_bytes: 64 * 1024 * 1024,
        max_conflicts: Some(250_000),
        max_decisions: Some(2_000_000),
        solver_clause_db_reduction_threshold_bytes: 64 * 1024 * 1024,
        max_proof_output_bytes: 64 * 1024 * 1024,
        max_derived_steps: MAX_PROOF_PRODUCING_RESOLUTION_STEPS,
        max_derived_literals: 2_000_000,
        max_hints: 4_000_000,
        max_pending_deletions: 250_000,
        max_codec_bytes: 192 * 1024 * 1024,
        max_backward_reconstruction_bytes: 64 * 1024 * 1024,
        ..ResolutionProofLimits::default()
    };
    resolution.validation.deadline = Some(deadline);
    resolution.validation.max_original_clauses = resolution.max_input_clauses;
    resolution.validation.max_original_literals = resolution.max_input_literals;
    resolution.validation.max_derived_steps = resolution.max_derived_steps;
    resolution.validation.max_derived_literals = resolution.max_derived_literals;
    resolution.validation.max_hints = resolution.max_hints;
    resolution.validation.max_work = MAX_PROOF_PRODUCING_BV_WORK_PER_LEMMA;
    resolution.validation.max_bytes = PROOF_PRODUCING_REPLAY_BYTES_PER_LEMMA;
    (
        BvExprProofLimits {
            max_expr_nodes: MAX_PROOF_PRODUCING_EXPR_NODES,
            max_expr_depth: MAX_PROOF_PRODUCING_EXPR_DEPTH,
            max_leaf_name_bytes: 1024 * 1024,
            max_internal_width: MAX_PROOF_PRODUCING_INTERNAL_BV_WIDTH,
            max_estimated_gate_work: MAX_PROOF_PRODUCING_GATE_WORK,
            max_construction_bytes: PROOF_PRODUCING_REPLAY_BYTES_PER_LEMMA,
            max_resolution_steps: MAX_PROOF_PRODUCING_RESOLUTION_STEPS,
            max_expanded_literals: MAX_PROOF_PRODUCING_EXPANDED_LITERALS,
            max_expansion_work: usize::try_from(MAX_PROOF_PRODUCING_BV_WORK_PER_LEMMA)
                .unwrap_or(usize::MAX),
            max_expansion_bytes: PROOF_PRODUCING_REPLAY_BYTES_PER_LEMMA,
            resolution,
        },
        deadline,
    )
}

/// Reserved SMT-LIB Core, BitVec-theory, and array vocabulary that the
/// uninterpreted-leaf abstraction must NEVER treat as a free function symbol
/// (#bitblast-original-clause-authority).
///
/// The list deliberately includes BV operators this lowerer does not (yet)
/// interpret — `bvudiv`, `rotate_left`, … — so an interpreted-theory gap stays
/// an honest `UnsupportedFragment` decline instead of silently becoming a
/// weaker free-leaf query. Abstracting them WOULD still be sound for UNSAT
/// (free leaves over-approximate every total interpretation), but declining
/// keeps this lane's diagnostics exact.
fn reserved_bool_bv_symbol(name: &str) -> bool {
    // `true`/`false`/`const` are deliberately ABSENT: the frontend lowers the
    // Boolean constants to `TermData::Const` (never named applications), and a
    // user `(declare-fun const …)` is an ordinary uninterpreted symbol — by
    // declaration identity it IS a free function, so abstracting it is exactly
    // right (the name-authority audit owns this invariant).
    matches!(
        name,
        // Core.
        "not" | "and" | "or" | "xor" | "=>" | "implies" | "=" | "distinct" | "ite"
            // Arrays (the exact finite-array lowering owns these).
            | "select" | "store"
            // BitVec theory, interpreted by this lowerer.
            | "bvnot" | "bvneg" | "bvadd" | "bvsub" | "bvmul" | "bvand" | "bvor" | "bvxor"
            | "bvnand" | "bvnor" | "bvxnor" | "bvshl" | "bvlshr" | "bvashr" | "concat"
            | "bvult" | "bvule" | "bvugt" | "bvuge" | "bvslt" | "bvsle" | "bvsgt" | "bvsge"
            // BitVec theory, currently outside this lowerer's fragment.
            | "bvudiv" | "bvurem" | "bvsdiv" | "bvsrem" | "bvsmod" | "bvcomp" | "bvredand"
            | "bvredor" | "repeat" | "rotate_left" | "rotate_right" | "zero_extend"
            | "sign_extend" | "extract"
    )
}

struct ProofProducingLowerer<'a> {
    terms: &'a TermStore,
    deadline: Instant,
    memo: HashMap<TermId, ProofProducingExpr>,
    memo_node_counts: HashMap<TermId, usize>,
    active: HashSet<TermId>,
    visited_nodes: usize,
    visited_edges: usize,
    constructed_expr_nodes: usize,
    depth: usize,
    resource_exhausted: bool,
    used_exact_finite_arrays: bool,
    exact_finite_array_work: usize,
    /// Opt-in (#bitblast-original-clause-authority): lower a Bool- or
    /// BV-sorted application of a NON-reserved symbol to one free leaf keyed
    /// by the application's canonical term identity, instead of rejecting the
    /// query. Sound for UNSAT only: every model of the exact query assigns
    /// each application term a single value, so it induces a valuation of the
    /// leaves — a refutation over free leaves therefore refutes the exact
    /// query, while a satisfiable abstraction proves nothing (the caller must
    /// NOT surface it as `Satisfiable`). Reserved Core/BV theory symbols are
    /// never abstracted; identical applications share one leaf; distinct
    /// applications never alias (congruence is deliberately forgotten).
    uninterpreted_leaves: bool,
    /// Opt-in, and strictly narrower than it sounds: lower a BOOL-SORTED
    /// application ONE of whose operands has a sort outside the finite
    /// Bool/BitVec/array universe (`Int`, `Char`, `Real`, …) to a single free
    /// BOOLEAN leaf keyed by the application's canonical term identity,
    /// WITHOUT descending into the operands.
    ///
    /// This is the standard propositional-skeleton abstraction, and it
    /// complements [`ProofProducingLowerer::take_uninterpreted_leaf`], which
    /// keys on the HEAD SYMBOL. Arithmetic relations (`<=`, `<`, …) are not
    /// reserved, so they already take the head-symbol leaf path; what needs
    /// this flag is the RESERVED Core heads `=` and `distinct`, whose
    /// interpreted arms eagerly lower their operands and therefore reach the
    /// `Int` sort rejection.
    ///
    /// NO NON-BOOLEAN LEAF IS EVER MINTED FOR SUCH AN OPERAND. `BvExpr` has
    /// only `Bool` and fixed-width `BitVec`, so an `Int` term modelled as a
    /// width-`w` leaf would be an UNDER-approximation: `w`+1 pairwise-distinct
    /// `Int` terms are satisfiable over the integers but refutable by
    /// pigeonhole at any finite width. Abstracting the enclosing Bool ATOM
    /// instead keeps the model map an identity on `Bool`, so every model of
    /// the exact query still induces a valuation of the leaves.
    non_finite_atom_leaves: bool,
    used_uninterpreted_leaves: bool,
}

impl<'a> ProofProducingLowerer<'a> {
    fn new(terms: &'a TermStore, deadline: Instant) -> Self {
        Self {
            terms,
            deadline,
            memo: HashMap::new(),
            memo_node_counts: HashMap::new(),
            active: HashSet::new(),
            visited_nodes: 0,
            visited_edges: 0,
            constructed_expr_nodes: 0,
            depth: 0,
            resource_exhausted: false,
            used_exact_finite_arrays: false,
            exact_finite_array_work: 0,
            uninterpreted_leaves: false,
            non_finite_atom_leaves: false,
            used_uninterpreted_leaves: false,
        }
    }

    /// Construct the uninterpreted-leaf variant. Kept as a separate
    /// constructor so every existing call site provably retains the exact
    /// (reject-on-UF) semantics without a flag audit.
    fn new_with_uninterpreted_leaves(terms: &'a TermStore, deadline: Instant) -> Self {
        Self {
            uninterpreted_leaves: true,
            ..Self::new(terms, deadline)
        }
    }

    /// Construct the uninterpreted-leaf variant EXTENDED by the Bool-atom
    /// abstraction over non-finitely-sorted operands.
    ///
    /// A separate constructor for the same reason as
    /// [`Self::new_with_uninterpreted_leaves`]: the pre-existing
    /// `authenticate_uf_leaf_bool_bv_unsat_query` entry point (and therefore
    /// the `CheckedQpfInstanceRefutation` lane that calls it) keeps a
    /// bit-identical accept set, because widening a lane that already exists
    /// would make it admit queries it previously refused.
    fn new_with_non_finite_atom_leaves(terms: &'a TermStore, deadline: Instant) -> Self {
        Self {
            non_finite_atom_leaves: true,
            ..Self::new_with_uninterpreted_leaves(terms, deadline)
        }
    }

    /// Whether `symbol` must be abstracted as a free leaf under the opt-in
    /// uninterpreted-leaf mode.
    ///
    /// Only plain named symbols outside the reserved Core/BV vocabulary
    /// qualify: indexed symbols are always theory syntax, and reserved names
    /// keep their exact interpreted lowering (or its honest "unsupported"
    /// rejection) so a fragment gap is never silently weakened into a free
    /// leaf. User declarations can never collide with reserved names — the
    /// frontend rejects redeclaring theory symbols — so a `bv`-prefixed USER
    /// function (e.g. `bvshadow`) is correctly abstracted by declaration
    /// identity, not spelling.
    fn take_uninterpreted_leaf(&mut self, symbol: &Symbol) -> bool {
        if !self.uninterpreted_leaves {
            return false;
        }
        let eligible =
            matches!(symbol, Symbol::Named(name) if !reserved_bool_bv_symbol(name.as_str()));
        if eligible {
            self.used_uninterpreted_leaves = true;
        }
        eligible
    }

    /// Whether this BOOL-SORTED application must be abstracted as ONE free
    /// Boolean leaf because an operand's sort lies outside the finite
    /// Bool/BitVec/array universe.
    ///
    /// Three properties are load-bearing and each has a pinned test:
    ///
    /// * It keys on the OPERAND SORT FAMILY, never on "lowering the operand
    ///   failed". A reserved-but-uninterpreted BV operator (`bvudiv`, …) has
    ///   BitVec-sorted operands, so it stays outside this predicate and keeps
    ///   declining with its operator named; likewise an out-of-range BitVec
    ///   width and an over-nested array. A fragment or envelope gap is never
    ///   silently weakened into a free leaf.
    /// * It reuses `used_uninterpreted_leaves` rather than adding a parallel
    ///   flag. That single bit is what turns a satisfiable abstraction into an
    ///   `UnsupportedFragment` DECLINE instead of a `Satisfiable` VETO; a new
    ///   flag not folded into that guard would itself be a proof hole.
    /// * It never fires without [`Self::non_finite_atom_leaves`], so the exact
    ///   entry point and the pre-existing UF-leaf entry point are unchanged.
    ///
    /// An operand outside the live term store is deliberately NOT eligible, so
    /// the "outside the live term store" rejection stays reachable.
    fn take_non_finite_atom_leaf(&mut self, args: &[TermId]) -> bool {
        if !self.non_finite_atom_leaves {
            return false;
        }
        let eligible = args.iter().any(|&arg| {
            self.terms.entry_stamp(arg).is_some()
                && array_finite::is_non_finite_source_sort(self.terms.sort(arg))
        });
        if eligible {
            self.used_uninterpreted_leaves = true;
        }
        eligible
    }

    fn lower_bool_terms(&mut self, terms: &[TermId]) -> Result<Vec<BvExpr>, String> {
        let mut lowered = Vec::new();
        if let Err(error) = lowered.try_reserve_exact(terms.len()) {
            self.resource_exhausted = true;
            return Err(format!("Bool expression allocation failed: {error}"));
        }
        for &term in terms {
            lowered.push(self.lower_bool(term)?);
        }
        Ok(lowered)
    }

    fn lower_bool(&mut self, term: TermId) -> Result<BvExpr, String> {
        match self.lower(term)? {
            ProofProducingExpr::Bool(expr) => Ok(expr),
            ProofProducingExpr::BitVec(_, width) => Err(format!(
                "term {} is BitVec({width}), not Bool",
                term.index()
            )),
            ProofProducingExpr::Array(_) => {
                Err(format!("term {} is Array, not Bool", term.index()))
            }
        }
    }

    fn lower_bv(&mut self, term: TermId) -> Result<(BvExpr, u32), String> {
        match self.lower(term)? {
            ProofProducingExpr::BitVec(expr, width) => Ok((expr, width)),
            ProofProducingExpr::Bool(_) => {
                Err(format!("term {} is Bool, not BitVec", term.index()))
            }
            ProofProducingExpr::Array(_) => {
                Err(format!("term {} is Array, not BitVec", term.index()))
            }
        }
    }

    fn lower(&mut self, term: TermId) -> Result<ProofProducingExpr, String> {
        if Instant::now() >= self.deadline {
            self.resource_exhausted = true;
            return Err("proof-producing lowering deadline exceeded".to_string());
        }
        let next_depth = self.depth.saturating_add(1);
        if next_depth > MAX_PROOF_PRODUCING_EXPR_DEPTH {
            self.resource_exhausted = true;
            return Err(format!(
                "proof-producing source depth exceeds {MAX_PROOF_PRODUCING_EXPR_DEPTH}"
            ));
        }
        self.depth = next_depth;
        let result = self.lower_inner(term);
        self.depth -= 1;
        result
    }

    fn lower_inner(&mut self, term: TermId) -> Result<ProofProducingExpr, String> {
        if self.terms.entry_stamp(term).is_none() {
            return Err(format!(
                "term {} is outside the live term store",
                term.index()
            ));
        }
        if self.memo.contains_key(&term) {
            let nodes = self.memo_node_counts[&term];
            self.charge_constructed_expr_nodes(nodes)?;
            return Ok(self.memo[&term].clone());
        }
        self.visited_nodes += 1;
        if self.visited_nodes > MAX_PROOF_PRODUCING_TERM_NODES {
            self.resource_exhausted = true;
            return Err(format!(
                "term DAG exceeds {MAX_PROOF_PRODUCING_TERM_NODES} nodes"
            ));
        }
        if !self.active.insert(term) {
            return Err("cyclic term DAG".to_string());
        }
        let sort = match array_finite::classify_source_sort(self.terms.sort(term)) {
            Ok(sort) => sort,
            Err(error) => {
                if error.is_resource_limit() {
                    self.resource_exhausted = true;
                }
                self.active.remove(&term);
                return Err(error.into_reason());
            }
        };
        let child_count = match self.terms.get(term) {
            TermData::Const(_) | TermData::Var(..) => 0,
            TermData::App(_, args) => args.len(),
            TermData::Not(_) => 1,
            TermData::Ite(..) => 3,
            _ => {
                self.active.remove(&term);
                return Err("unsupported Bool/BitVec source node".to_string());
            }
        };
        self.visited_edges = self.visited_edges.saturating_add(child_count);
        if self.visited_edges > MAX_PROOF_PRODUCING_TERM_EDGES {
            self.resource_exhausted = true;
            self.active.remove(&term);
            return Err(format!(
                "term DAG exceeds {MAX_PROOF_PRODUCING_TERM_EDGES} child edges"
            ));
        }
        let data = match self.clone_supported_data(term) {
            Ok(data) => data,
            Err(error) => {
                self.active.remove(&term);
                return Err(error);
            }
        };
        let result = match sort {
            array_finite::FiniteSourceSort::Bool => self.lower_bool_node(term, data),
            array_finite::FiniteSourceSort::BitVec(width) => self.lower_bv_node(term, width, data),
            array_finite::FiniteSourceSort::Array(shape) => {
                self.lower_exact_finite_array_node(term, shape, data)
            }
        };
        self.active.remove(&term);
        let result = result?;
        let expr_nodes = match proof_producing_expr_nodes(&result) {
            Ok(nodes) => nodes,
            Err(error) => {
                self.resource_exhausted = true;
                return Err(error);
            }
        };
        self.charge_constructed_expr_nodes(expr_nodes)?;
        self.memo_node_counts.insert(term, expr_nodes);
        self.memo.insert(term, result.clone());
        Ok(result)
    }

    fn charge_constructed_expr_nodes(&mut self, nodes: usize) -> Result<(), String> {
        let actual = self.constructed_expr_nodes.saturating_add(nodes);
        if actual > MAX_PROOF_PRODUCING_CONSTRUCTED_EXPR_NODES {
            self.resource_exhausted = true;
            return Err(format!(
                "lowered BvExpr construction exceeds {MAX_PROOF_PRODUCING_CONSTRUCTED_EXPR_NODES} nodes"
            ));
        }
        self.constructed_expr_nodes = actual;
        Ok(())
    }

    fn clone_supported_data(&mut self, term: TermId) -> Result<TermData, String> {
        match self.terms.get(term) {
            TermData::Const(Constant::Bool(value)) => Ok(TermData::Const(Constant::Bool(*value))),
            TermData::Const(Constant::BitVec { value, width }) if value.to_u128().is_some() => {
                Ok(TermData::Const(Constant::BitVec {
                    value: value.clone(),
                    width: *width,
                }))
            }
            TermData::Const(_) => Err("unsupported Bool/BV/array constant".to_string()),
            TermData::Var(_, id) => Ok(TermData::Var(String::new(), *id)),
            TermData::Not(inner) => Ok(TermData::Not(*inner)),
            TermData::Ite(condition, then_term, else_term) => {
                Ok(TermData::Ite(*condition, *then_term, *else_term))
            }
            TermData::App(symbol, args) => {
                if symbol.name().len() > 32 {
                    return Err("unsupported Bool/BV/array operator".to_string());
                }
                let symbol = match symbol {
                    Symbol::Named(name) => Symbol::Named(name.clone()),
                    Symbol::Indexed(name, indices) if indices.len() <= 2 => {
                        Symbol::Indexed(name.clone(), indices.clone())
                    }
                    _ => return Err("unsupported indexed Bool/BV/array operator".to_string()),
                };
                let mut cloned_args = Vec::new();
                if let Err(error) = cloned_args.try_reserve_exact(args.len()) {
                    self.resource_exhausted = true;
                    return Err(format!("Bool/BitVec argument allocation failed: {error}"));
                }
                cloned_args.extend_from_slice(args);
                Ok(TermData::App(symbol, cloned_args))
            }
            _ => Err("unsupported Bool/BV/array source node".to_string()),
        }
    }

    fn lower_bool_node(
        &mut self,
        term: TermId,
        data: TermData,
    ) -> Result<ProofProducingExpr, String> {
        let expr = match data {
            TermData::Const(Constant::Bool(value)) => BvExpr::const_val(u128::from(value), 1),
            TermData::Var(_, _) => BvExpr::leaf(&format!("proof_bool_{}", term.index()), 1),
            TermData::Not(inner) => BvExpr::not(self.lower_bool(inner)?),
            TermData::App(Symbol::Named(name), args) if name == "select" => {
                match self.lower_exact_finite_array_select(
                    term,
                    &args,
                    &array_finite::FiniteSortShape::bool_scalar(),
                )? {
                    ProofProducingExpr::Bool(expr) => expr,
                    _ => {
                        return Err(
                            "array select did not produce its declared Bool sort".to_string()
                        )
                    }
                }
            }
            TermData::App(symbol, args) => {
                if self.take_uninterpreted_leaf(&symbol) || self.take_non_finite_atom_leaf(&args) {
                    // One free Boolean leaf per canonical application term:
                    // the `proof_bool_{index}` namespace is shared with `Var`
                    // leaves, and distinct terms have distinct indices, so an
                    // application leaf can never alias a variable leaf.
                    //
                    // The second disjunct covers a RESERVED Core head (`=`,
                    // `distinct`) over non-finitely-sorted operands: the whole
                    // atom becomes one Boolean leaf and the operands are never
                    // visited, so no `Int` term is ever given a finite width.
                    BvExpr::leaf(&format!("proof_bool_{}", term.index()), 1)
                } else {
                    self.lower_bool_app(&symbol, &args)?
                }
            }
            TermData::Ite(condition, then_term, else_term) => {
                let condition = self.lower_bool(condition)?;
                let then_expr = self.lower_bool(then_term)?;
                let else_expr = self.lower_bool(else_term)?;
                BvExpr::or(
                    BvExpr::and(condition.clone(), then_expr),
                    BvExpr::and(BvExpr::not(condition), else_expr),
                )
            }
            other => return Err(format!("unsupported Bool node {other:?}")),
        };
        Ok(ProofProducingExpr::Bool(expr))
    }

    fn lower_bool_app(&mut self, symbol: &Symbol, args: &[TermId]) -> Result<BvExpr, String> {
        let Symbol::Named(name) = symbol else {
            return Err(format!(
                "indexed operator `{symbol}` is not a canonical Bool/BV predicate"
            ));
        };
        match name.as_str() {
            "and" => self.lower_balanced_bool(args, true, BvExpr::and),
            "or" => self.lower_balanced_bool(args, false, BvExpr::or),
            "not" if args.len() == 1 => Ok(BvExpr::not(self.lower_bool(args[0])?)),
            "=>" | "implies" if args.len() == 2 => Ok(BvExpr::or(
                BvExpr::not(self.lower_bool(args[0])?),
                self.lower_bool(args[1])?,
            )),
            "xor" if args.len() == 2 => Ok(BvExpr::xor(
                self.lower_bool(args[0])?,
                self.lower_bool(args[1])?,
            )),
            "=" if args.len() == 2 => match (self.lower(args[0])?, self.lower(args[1])?) {
                (ProofProducingExpr::Bool(lhs), ProofProducingExpr::Bool(rhs)) => {
                    Ok(BvExpr::eq(lhs, rhs))
                }
                (
                    ProofProducingExpr::BitVec(lhs, lhs_width),
                    ProofProducingExpr::BitVec(rhs, rhs_width),
                ) => {
                    Self::require_same_width(name, lhs_width, rhs_width)?;
                    Ok(BvExpr::eq(lhs, rhs))
                }
                (ProofProducingExpr::Array(lhs), ProofProducingExpr::Array(rhs)) => {
                    self.lower_exact_finite_array_equality(lhs, rhs)
                }
                _ => Err("equality operands have different Bool/BV sorts".to_string()),
            },
            "bvult" | "bvule" | "bvugt" | "bvuge" | "bvslt" | "bvsle" | "bvsgt" | "bvsge"
                if args.len() == 2 =>
            {
                let (lhs, lhs_width) = self.lower_bv(args[0])?;
                let (rhs, rhs_width) = self.lower_bv(args[1])?;
                Self::require_same_width(name, lhs_width, rhs_width)?;
                Ok(match name.as_str() {
                    "bvult" => Self::unsigned_lt(lhs, rhs),
                    "bvule" => BvExpr::not(Self::unsigned_lt(rhs, lhs)),
                    "bvugt" => Self::unsigned_lt(rhs, lhs),
                    "bvuge" => BvExpr::not(Self::unsigned_lt(lhs, rhs)),
                    "bvslt" => Self::signed_lt(lhs, rhs, lhs_width),
                    "bvsle" => BvExpr::not(Self::signed_lt(rhs, lhs, lhs_width)),
                    "bvsgt" => Self::signed_lt(rhs, lhs, lhs_width),
                    "bvsge" => BvExpr::not(Self::signed_lt(lhs, rhs, lhs_width)),
                    _ => unreachable!("guarded comparison"),
                })
            }
            _ => Err(format!("unsupported Bool/BV predicate `{symbol}`")),
        }
    }

    fn lower_balanced_bool(
        &mut self,
        args: &[TermId],
        identity: bool,
        combine: fn(BvExpr, BvExpr) -> BvExpr,
    ) -> Result<BvExpr, String> {
        let lowered = self.lower_bool_terms(args)?;
        match balanced_bool_expr(lowered, identity, combine) {
            Ok(expression) => Ok(expression),
            Err(error) => {
                self.resource_exhausted = true;
                Err(error)
            }
        }
    }

    fn lower_bv_node(
        &mut self,
        term: TermId,
        expected_width: u32,
        data: TermData,
    ) -> Result<ProofProducingExpr, String> {
        let (expr, width) = match data {
            TermData::Const(Constant::BitVec { value, width }) => {
                let value = value.to_u128().ok_or_else(|| {
                    format!("BitVec constant does not fit the {MAX_PROOF_PRODUCING_INTERNAL_BV_WIDTH}-bit proof range")
                })?;
                (BvExpr::const_val(value, width), width)
            }
            TermData::Var(_, _) => (
                BvExpr::leaf(&format!("proof_bv_{}", term.index()), expected_width),
                expected_width,
            ),
            TermData::App(Symbol::Named(name), args) if name == "select" => {
                let expected = array_finite::FiniteSortShape::bitvec_scalar(expected_width);
                match self.lower_exact_finite_array_select(term, &args, &expected)? {
                    ProofProducingExpr::BitVec(expr, width) => (expr, width),
                    _ => {
                        return Err(
                            "array select did not produce its declared BitVec sort".to_string()
                        )
                    }
                }
            }
            TermData::App(symbol, args) => {
                if self.take_uninterpreted_leaf(&symbol) {
                    // One free BV leaf per canonical application term at the
                    // application's declared width (`classify_source_sort`
                    // already enforced the internal width ceiling, exactly as
                    // for `Var` leaves).
                    (
                        BvExpr::leaf(&format!("proof_bv_{}", term.index()), expected_width),
                        expected_width,
                    )
                } else {
                    self.lower_bv_app(&symbol, &args)?
                }
            }
            TermData::Ite(condition, then_term, else_term) => {
                let condition = self.lower_bool(condition)?;
                let (then_expr, then_width) = self.lower_bv(then_term)?;
                let (else_expr, else_width) = self.lower_bv(else_term)?;
                Self::require_same_width("ite", then_width, else_width)?;
                let mask = BvExpr::sign_ext(condition, then_width - 1);
                (
                    BvExpr::or(
                        BvExpr::and(mask.clone(), then_expr),
                        BvExpr::and(BvExpr::not(mask), else_expr),
                    ),
                    then_width,
                )
            }
            other => return Err(format!("unsupported BitVec node {other:?}")),
        };
        if width != expected_width {
            return Err(format!(
                "term {} lowers to width {width}, expected {expected_width}",
                term.index()
            ));
        }
        Ok(ProofProducingExpr::BitVec(expr, width))
    }

    fn lower_bv_app(&mut self, symbol: &Symbol, args: &[TermId]) -> Result<(BvExpr, u32), String> {
        if let Symbol::Indexed(name, indices) = symbol {
            if args.is_empty() {
                if let (Some(value), [width]) = (name.strip_prefix("bv"), indices.as_slice()) {
                    let value = value
                        .parse::<u128>()
                        .map_err(|_| format!("malformed indexed BV constant `{symbol}`"))?;
                    return Ok((BvExpr::const_val(value, *width), *width));
                }
            }
            let [arg] = args else {
                return Err(format!("indexed operator `{symbol}` requires one argument"));
            };
            return match (name.as_str(), indices.as_slice()) {
                ("zero_extend", [added]) => {
                    let (inner, width) = self.lower_bv(*arg)?;
                    let out = width
                        .checked_add(*added)
                        .ok_or_else(|| "zero_extend width overflow".to_string())?;
                    Ok((BvExpr::zero_ext(inner, *added), out))
                }
                ("sign_extend", [added]) => {
                    let (inner, width) = self.lower_bv(*arg)?;
                    let out = width
                        .checked_add(*added)
                        .ok_or_else(|| "sign_extend width overflow".to_string())?;
                    Ok((BvExpr::sign_ext(inner, *added), out))
                }
                ("extract", [high, low]) if high >= low => {
                    let (inner, width) = self.lower_bv(*arg)?;
                    if *high >= width {
                        return Err(format!("extract high bit {high} exceeds width {width}"));
                    }
                    Ok((BvExpr::extract(inner, *high, *low), high - low + 1))
                }
                _ => Err(format!("unsupported indexed BitVec operator `{symbol}`")),
            };
        }

        let name = symbol.name();
        if name == "bvnot" || name == "bvneg" {
            let [arg] = args else {
                return Err(format!("`{name}` requires one argument"));
            };
            let (inner, width) = self.lower_bv(*arg)?;
            return Ok((
                if name == "bvnot" {
                    BvExpr::not(inner)
                } else {
                    BvExpr::sub(BvExpr::const_val(0, width), inner)
                },
                width,
            ));
        }
        let [lhs_term, rhs_term] = args else {
            return Err(format!("`{name}` requires two arguments"));
        };
        let (lhs, lhs_width) = self.lower_bv(*lhs_term)?;
        let (rhs, rhs_width) = self.lower_bv(*rhs_term)?;
        if name == "concat" {
            let width = lhs_width
                .checked_add(rhs_width)
                .ok_or_else(|| "concat width overflow".to_string())?;
            let high = BvExpr::zero_ext(lhs, rhs_width);
            let low = BvExpr::zero_ext(rhs, lhs_width);
            let shifted = BvExpr::shl(high, BvExpr::const_val(u128::from(rhs_width), width));
            return Ok((BvExpr::or(shifted, low), width));
        }
        Self::require_same_width(name, lhs_width, rhs_width)?;
        let expr = match name {
            "bvadd" => BvExpr::add(lhs, rhs),
            "bvsub" => BvExpr::sub(lhs, rhs),
            "bvmul" => BvExpr::mul(lhs, rhs),
            "bvand" => BvExpr::and(lhs, rhs),
            "bvor" => BvExpr::or(lhs, rhs),
            "bvxor" => BvExpr::xor(lhs, rhs),
            "bvnand" => BvExpr::not(BvExpr::and(lhs, rhs)),
            "bvnor" => BvExpr::not(BvExpr::or(lhs, rhs)),
            "bvxnor" => BvExpr::not(BvExpr::xor(lhs, rhs)),
            "bvshl" => BvExpr::shl(lhs, rhs),
            "bvlshr" => BvExpr::lshr(lhs, rhs),
            "bvashr" => BvExpr::ashr(lhs, rhs),
            _ => return Err(format!("unsupported BitVec operator `{symbol}`")),
        };
        Ok((expr, lhs_width))
    }

    fn require_same_width(name: &str, lhs: u32, rhs: u32) -> Result<(), String> {
        if lhs == rhs {
            Ok(())
        } else {
            Err(format!("`{name}` width mismatch: {lhs} vs {rhs}"))
        }
    }

    fn unsigned_lt(lhs: BvExpr, rhs: BvExpr) -> BvExpr {
        BvExpr::not(BvExpr::carry_out_sub(lhs, rhs))
    }

    /// Two's-complement order is unsigned order after flipping the sign bit.
    /// This uses only checked XOR and subtraction-carry gates already present
    /// in the clean bit-blast kernel.
    fn signed_lt(lhs: BvExpr, rhs: BvExpr, width: u32) -> BvExpr {
        let sign_mask = BvExpr::const_val(1_u128 << (width - 1), width);
        Self::unsigned_lt(
            BvExpr::xor(lhs, sign_mask.clone()),
            BvExpr::xor(rhs, sign_mask),
        )
    }
}

