pub(super) trait Control {
    fn offer(&mut self, work: usize, bytes: usize) -> Result<(), QueryError>;
    fn exhausted(&mut self) -> QueryError;
}

struct Borrowed<'budget, 'owner>(&'budget mut WorkBudget<'owner>);
impl Control for Borrowed<'_, '_> {
    fn offer(&mut self, work: usize, bytes: usize) -> Result<(), QueryError> {
        self.0.admit(work, bytes)
    }
    fn exhausted(&mut self) -> QueryError {
        self.0.refuse_exhaustion()
    }
}

struct Legacy;
impl Control for Legacy {
    fn offer(&mut self, _: usize, _: usize) -> Result<(), QueryError> {
        Ok(())
    }
    fn exhausted(&mut self) -> QueryError {
        QueryError::Exhausted
    }
}

pub(super) fn legacy_input(problem: &ChcProblem) -> Result<String, QueryError> {
    input::build(problem, &mut Legacy)
}

/// Exact canonical bytes and their immutable source, NOT a source/proof seal.
///
/// This carrier retains the SAME caller ledger. Original source allocation,
/// source destruction, model decoding/typing and native replay remain outside.
/// Optional with_sha256 owns only the retained canonical-byte digest; with_input
/// does not own legacy hashing. No Clone or unrestricted owned-byte export exists.
/// Ordinary Drop disposes prepaid DATA but supplies no accepted final fence;
/// only checked consumption observes the post-cleanup owner boundary.
pub struct PreparedNormalizedChcInput<'source, 'budget, 'owner> {
    source: &'source ChcProblem,
    bytes: String,
    work: &'budget mut WorkBudget<'owner>,
}

impl PreparedNormalizedChcInput<'_, '_, '_> {
    /// Hash ONLY these retained canonical bytes under the SAME original ledger.
    ///
    /// Portable FIPS180-4 SHA-256 uses paid fixed buffers and bounded rounds,
    /// not a platform backend or the legacy normalizer. Digest/hex and callback
    /// captures die before bytes and the final original poll. Returned DATA is
    /// neither a proof, source seal nor an owned native-solve credential.
    /// Caller copies/destructors remain caller-owned; run inside
    /// OriginalAdmission::with_work for shared typed-error/panic latching.
    pub fn with_sha256(
        self,
        operation: impl FnOnce(&ChcProblem, &str, &str, &mut WorkBudget<'_>) -> Result<(), QueryError>,
    ) -> Result<(), QueryError> {
        let Self {
            source,
            bytes,
            work,
        } = self;
        let result = catch_unwind(AssertUnwindSafe(|| {
            digest::consume(source, &bytes, work, operation)
        }));
        drop(bytes);
        let final_poll = work.charge(0);
        match result {
            Err(payload) => resume_unwind(payload),
            Ok(result) => {
                result?;
                final_poll
            }
        }
    }

    /// Consume through one UNIT callback, then discard callback captures and
    /// generated bytes BEFORE the original final poll. Captures may export copies:
    /// this cooperative seam does not price or prevent caller side channels.
    /// Run inside OriginalAdmission::with_work to fold returned errors/panics into
    /// the original shared latch, without another owner/grant/relative timer.
    pub fn with_input(
        self,
        operation: impl FnOnce(&ChcProblem, &str, &mut WorkBudget<'_>) -> Result<(), QueryError>,
    ) -> Result<(), QueryError> {
        let Self {
            source,
            bytes,
            work,
        } = self;
        let result = catch_unwind(AssertUnwindSafe(|| {
            work.charge(0)?;
            operation(source, &bytes, work)
        }));
        drop(bytes);
        let final_poll = work.charge(0);
        match result {
            Err(payload) => resume_unwind(payload),
            Ok(result) => {
                result?;
                final_poll
            }
        }
    }
}

/// Prepare exact legacy normalized-input bytes using actual original admission.
///
/// Datatype declarations and sorts are explicitly unsupported, even unused or
/// hidden inside an expression. Bool/Int/Real/BV/Array/UF spelling is structural,
/// not typing: raw widths, unknown predicate IDs and raw rationals retain their
/// legacy bytes. Every shared/unchosen edge is walked; no semantic simplification
/// or original Arc clone occurs. Paid fallible buffers/mergesort replace opaque
/// formatting, joins, serde, BTree construction and sorting in this accepted path.
/// Backend allocator execution is cooperative, not hard-preempted or RSS-priced.
pub fn prepare_normalized_chc_input_with_work<'source, 'budget, 'owner>(
    problem: &'source ChcProblem,
    work: &'budget mut WorkBudget<'owner>,
) -> Result<PreparedNormalizedChcInput<'source, 'budget, 'owner>, QueryError> {
    work.charge(0)?;
    let result = input::build(problem, &mut Borrowed(work));
    // build has already discarded its labels, ordering/traversal and row scratch.
    let final_poll = work.charge(0);
    match result {
        Err(error) => {
            final_poll?;
            Err(error)
        }
        Ok(bytes) => {
            if let Err(error) = final_poll {
                drop(bytes);
                work.charge(0)?;
                return Err(error);
            }
            if let Err(error) =
                work.charge(std::mem::size_of::<PreparedNormalizedChcInput<'_, '_, '_>>())
            {
                drop(bytes);
                work.charge(0)?;
                return Err(error);
            }
            Ok(PreparedNormalizedChcInput {
                source: problem,
                bytes,
                work,
            })
        }
    }
}
