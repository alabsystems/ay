//! Streaming canonical JSON comparison; no second envelope-sized allocation.

use super::{Control, QfEnvelopePreparationError as Error, QfInvariantModelEnvelope};

pub(super) fn check<C: Control>(
    envelope: &QfInvariantModelEnvelope,
    expected: &[u8],
    control: &mut C,
) -> Result<(), Error> {
    control.offer(std::mem::size_of::<Comparison<'_, '_, C>>(), 0)?;
    let mut output = Comparison {
        expected,
        at: 0,
        control,
    };
    output.bytes(b"{\"schema\":")?;
    output.string(&envelope.schema)?;
    output.bytes(b",\"schema_version\":")?;
    output.number(envelope.schema_version)?;
    output.bytes(b",\"role\":")?;
    output.string(&envelope.role)?;
    output.bytes(b",\"model_format\":")?;
    output.string(&envelope.model_format)?;
    output.bytes(b",\"normalized_input_sha256\":")?;
    output.string(&envelope.normalized_input_sha256)?;
    output.bytes(b",\"predicate_count\":")?;
    output.number(envelope.predicate_count)?;
    output.bytes(b",\"model_sha256\":")?;
    output.string(&envelope.model_sha256)?;
    output.bytes(b",\"model_smtlib\":")?;
    output.string(&envelope.model_smtlib)?;
    output.bytes(b"}")?;
    if output.at != expected.len() {
        return Err(Error::NonCanonical);
    }
    Ok(())
}
struct Comparison<'bytes, 'control, C> {
    expected: &'bytes [u8],
    at: usize,
    control: &'control mut C,
}
impl<C: Control> Comparison<'_, '_, C> {
    fn bytes(&mut self, bytes: &[u8]) -> Result<(), Error> {
        // Each byte reads one generated byte and one supplied byte.
        let work = bytes
            .len()
            .checked_mul(2)
            .ok_or_else(|| self.control.allocation_failed())?;
        self.control.offer(work, 0)?;
        let end = self
            .at
            .checked_add(bytes.len())
            .ok_or_else(|| self.control.allocation_failed())?;
        if self.expected.get(self.at..end) != Some(bytes) {
            return Err(Error::NonCanonical);
        }
        self.at = end;
        Ok(())
    }
    fn string(&mut self, text: &str) -> Result<(), Error> {
        self.bytes(b"\"")?;
        const HEX: &[u8; 16] = b"0123456789abcdef";
        for index in 0..text.len() {
            self.control.offer(1, 0)?;
            let byte = text.as_bytes()[index];
            match byte {
                b'"' => self.bytes(b"\\\"")?,
                b'\\' => self.bytes(b"\\\\")?,
                8 => self.bytes(b"\\b")?,
                9 => self.bytes(b"\\t")?,
                10 => self.bytes(b"\\n")?,
                12 => self.bytes(b"\\f")?,
                13 => self.bytes(b"\\r")?,
                0..=31 => {
                    // Six fixed writes, two HEX reads, four index scalar steps.
                    self.control.offer(12, 0)?;
                    self.bytes(&[
                        b'\\',
                        b'u',
                        b'0',
                        b'0',
                        HEX[(byte >> 4) as usize],
                        HEX[(byte & 15) as usize],
                    ])?;
                }
                _ => {
                    self.control.offer(1, 0)?;
                    self.bytes(&[byte])?;
                }
            }
        }
        self.bytes(b"\"")
    }
    fn number(&mut self, mut value: u64) -> Result<(), Error> {
        self.control.offer(20, 0)?;
        let mut digits = [0u8; 20];
        let mut start = digits.len();
        loop {
            self.control.offer(3, 0)?;
            start -= 1;
            digits[start] = b'0' + (value % 10) as u8;
            value /= 10;
            if value == 0 {
                break;
            }
        }
        self.bytes(&digits[start..])
    }
}
