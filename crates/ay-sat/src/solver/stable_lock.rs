//! One-shot stable-mode lock gated by a learned-clause shape classifier
//! (`--sat-stable-lock-at`), ported from kissat-eda (SAT Competition 2026,
//! Yalun; MIT, a Kissat 4.0.2 derivative: `reduce.c:17-117`, `mode.c:217-245`,
//! `search.c:202-209`).
//!
//! At a fixed conflict count kissat-eda reads the (glue, size) histogram of
//! the learned clauses created so far and scores it with a logistic
//! regression. A non-negative score locks stable mode for the rest of the
//! run. On the multiplier-miter family (booth_dadda, bwmdm_28_2) the lock is
//! where most of kissat-eda's 2.3x over Kissat 4.0.2 comes from: 12-14 percent
//! fewer ticks per conflict and a quarter fewer conflicts on booth_dadda,
//! where modes that keep switching restart about 93K times per 3M conflicts
//! against 700 when locked. The classifier keeps the lock off the SAT-heavy
//! families where stable-only search is worse.
//!
//! Features, as kissat-eda computes them: for glue 1..=30 and size
//! glue+1..=30 (435 bins, glue-major), `ln(1 + count)`, divided by the sum of
//! all 435; score = bias + weights . features. The weights are kissat-eda's,
//! verbatim.

