/// Counts of learned clauses by (glue, size), for glue and size up to 30.
#[derive(Clone)]
pub(super) struct LearnedShapeHistogram {
    counts: Vec<u64>,
}

impl LearnedShapeHistogram {
    pub(super) fn new() -> Self {
        Self {
            counts: vec![0; (SHAPE_MAX + 1) * (SHAPE_MAX + 1)],
        }
    }

    pub(super) fn build_admitted<A: super::construction::Construction>(
        a: &A,
    ) -> Result<Self, A::Error> {
        a.metadata::<Self>()?;
        Ok(Self {
            counts: a.filled((SHAPE_MAX + 1) * (SHAPE_MAX + 1), 0)?,
        })
    }

    /// Count one learned clause (kissat-eda counts every new large redundant
    /// clause; sizes and glues above 30 fall outside every bin).
    #[inline]
    pub(super) fn record(&mut self, glue: u32, size: usize) {
        let glue = glue as usize;
        if glue <= SHAPE_MAX && size <= SHAPE_MAX {
            self.counts[glue * (SHAPE_MAX + 1) + size] += 1;
        }
    }

    /// The classifier's score: lock stable mode when it is non-negative.
    pub(super) fn score(&self) -> f64 {
        self.score_with(LOGREG_B, &LOGREG_W)
    }

    /// kissat-eda-3's second score (`--sat-stable-lock-second-gate`).
    pub(super) fn second_score(&self) -> f64 {
        self.score_with(LOGREG_STB2_B, &LOGREG_STB2_W)
    }

    fn score_with(&self, bias: f64, weights: &[f64; SHAPE_BINS]) -> f64 {
        let mut features = [0.0f64; SHAPE_BINS];
        let mut sum = 0.0;
        let mut k = 0;
        for glue in 1..=SHAPE_MAX {
            for size in glue + 1..=SHAPE_MAX {
                let v = (self.counts[glue * (SHAPE_MAX + 1) + size] as f64).ln_1p();
                features[k] = v;
                sum += v;
                k += 1;
            }
        }
        let inv = 1.0 / (sum + 1e-8);
        bias + weights
            .iter()
            .zip(features.iter())
            .map(|(w, f)| w * f * inv)
            .sum::<f64>()
    }
}

impl Solver {
    /// Count a newly learned clause for the stable-lock classifier.
    #[inline]
    pub(super) fn record_learned_shape(&mut self, glue: u32, size: usize) {
        if let Some(histogram) = self.cold.learned_shapes.as_mut() {
            histogram.record(glue, size);
        }
    }

    /// Called once, when the conflict count reaches `--sat-stable-lock-at`:
    /// score the histogram (unless `--sat-stable-lock-ungated`) and lock stable
    /// mode on a non-negative score. From focused mode the lock takes effect at
    /// the next restart check, through the ordinary switch into stable mode.
    #[cold]
    pub(super) fn decide_stable_lock(&mut self) {
        // Once: inprocessing (backbone, probing) also counts conflicts, so the
        // search loop can first see a count past the threshold, not equal to it.
        self.cold.stable_lock_at = u64::MAX;
        let ungated = ay_core::sat_ab_switches().stable_lock_ungated == Some(true);
        let score = self
            .cold
            .learned_shapes
            .as_ref()
            .map_or(0.0, |histogram| histogram.score());
        self.stats.stable_lock_score_milli = (score * 1000.0) as i64;
        let second_gate = ay_core::sat_ab_switches().stable_lock_second_gate == Some(true);
        let second = if second_gate {
            self.cold
                .learned_shapes
                .as_ref()
                .map_or(0.0, |histogram| histogram.second_score())
        } else {
            0.0
        };
        if !(ungated || score >= 0.0) {
            // kissat-eda-2 keeps its usage-based retention only where it locks
            // (`search.c:206`): `--sat-stable-lock-revert-two-stage` returns
            // the other formulas to glue tiers here.
            if ay_core::sat_ab_switches().stable_lock_revert_two_stage == Some(true) {
                self.two_stage_clause_management = false;
            }
            return;
        }
        // kissat-eda-3: the first score alone keeps the usage retention, both
        // together lock stable mode.
        if second_gate && !ungated && second < 0.0 {
            if ay_core::sat_ab_switches().stable_lock_two_stage == Some(true) {
                self.two_stage_clause_management = true;
            }
            return;
        }
        if self.cold.mode_lock != cold::ModeLock::None {
            return;
        }
        self.stats.stable_locked_at = self.num_conflicts;
        // `--sat-stable-lock-two-stage`: the usage-based retention kissat-eda
        // pairs with the lock, switched on here, so formulas the classifier
        // does not lock keep glue tiers throughout.
        if ay_core::sat_ab_switches().stable_lock_two_stage == Some(true) {
            self.two_stage_clause_management = true;
        }
        if self.stable_mode {
            self.cold.mode_lock = cold::ModeLock::Stable;
        } else {
            self.cold.stable_lock_pending = true;
            self.cold.stabilize_tick_limit = self.num_conflicts;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_empty_histogram_scores_the_bias() {
        assert!((LearnedShapeHistogram::new().score() - LOGREG_B).abs() < 1e-12);
    }

    #[test]
    fn long_near_glue_clauses_score_positive_and_short_low_glue_negative() {
        // kissat-eda's positive weight sits on glue 13-20 with size glue+1,
        // its most negative on glue 1, size 3.
        let mut miter = LearnedShapeHistogram::new();
        for glue in 13..=20 {
            for _ in 0..1000 {
                miter.record(glue, glue as usize + 1);
            }
        }
        assert!(miter.score() > 0.0);
        let mut short = LearnedShapeHistogram::new();
        for _ in 0..1000 {
            short.record(1, 3);
        }
        assert!(short.score() < 0.0);
    }
}
