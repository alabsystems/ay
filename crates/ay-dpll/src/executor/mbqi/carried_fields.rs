//! Binder-sort elements that datatype values carry (2026-09-23 hunt, D1).
//!
//! A finite-universe argument over an uninterpreted sort `U` enumerates `U`'s
//! universe. A datatype with a field of sort `U` is an implicit generator of
//! that universe: `(declare-datatype W ((w (g U)) (w2)))` gives every
//! `w`-value its own `U` element, which no ground `U`-term need denote. The
//! EPR SAT certificate, MBQI's instantiation candidates and the quantified
//! model gate all name those elements through the helpers here: selector terms
//! that follow a ground datatype term's value under the model, and the EUF
//! model's own terms for elements the fields do not reach.

use std::borrow::Cow;

use ay_core::kani_compat::{DetHashMap as HashMap, DetHashSet as HashSet};
use ay_core::{Sort, Symbol, TermData, TermId};

use super::super::model::EvalValue;
use super::super::Executor;
use crate::ematching::contains_quantifier;

/// Most constructor levels followed below one ground datatype term when
/// naming the binder-sort elements its model value carries.
const MAX_CARRIED_FIELD_DEPTH: usize = 8;

/// Most selector terms one carried-field walk mints.
const MAX_CARRIED_FIELD_TERMS: usize = 256;

/// Selector terms naming the binder-sort elements held in datatype fields,
/// from [`Executor::carried_binder_field_terms`].
pub(in crate::executor) struct CarriedFieldTerms {
    /// Per binder sort, the selector terms denoting the carried elements.
    pub(in crate::executor) by_sort: HashMap<Sort, Vec<TermId>>,
    /// Whether every carried element is named in `by_sort`.
    pub(in crate::executor) complete: bool,
    /// Datatype terms, reached through a definite constructor of a carrier,
    /// whose own constructor the model leaves open (no definite tester): a
    /// selector chain no solver term registers.
    pub(in crate::executor) frontier: Vec<TermId>,
}

impl Executor {
    /// Steps 2 and 3 of the EPR certificate: the universe of every binder
    /// sort, or `None` when it is not generated by ground terms.
    ///
    /// A datatype value carries binder-sort elements that no ground term of
    /// the binder sort need denote: `a = w(e)` holds `e` whatever the ground
    /// `U`-terms are, and shrinking `U` to their values would shrink `W` and
    /// falsify `(distinct a0 a1 a2 a3)` (D1). Those elements join the
    /// universe through the selector terms that denote them under the current
    /// model; a carrier the walk cannot follow exactly declines.
    pub(super) fn epr_universe_with_carried_fields(
        &mut self,
        snapshot: &[TermId],
        binder_sorts: &HashSet<Sort>,
    ) -> Option<HashMap<Sort, Vec<TermId>>> {
        let carriers = self.binder_universe_carriers(snapshot, binder_sorts)?;
        let mut ground_by_sort =
            crate::ematching::collect_ground_terms_by_sort(&self.ctx.terms, snapshot);
        if carriers.is_empty() {
            return Some(ground_by_sort);
        }
        let carried =
            self.carried_binder_field_terms(&carriers, binder_sorts, &mut Self::model_tester_holds);
        if !carried.complete {
            return None;
        }
        for (sort, fields) in carried.by_sort {
            let universe = ground_by_sort.entry(sort).or_default();
            for t in fields {
                if !universe.contains(&t) {
                    universe.push(t);
                }
            }
        }
        Some(ground_by_sort)
    }

    /// A tester's value under the current model, as the solver's own
    /// evaluator reads it; `None` when it is not definite.
    fn model_tester_holds(&self, tester: TermId) -> Option<bool> {
        match self.evaluate_term(self.last_model.as_ref()?, tester) {
            EvalValue::Bool(b) => Some(b),
            _ => None,
        }
    }

    /// MBQI instantiation candidates per sort: `ground_by_sort`, extended for
    /// every plain uninterpreted binder sort of `quants` that a ground
    /// datatype term carries by the selector terms naming the elements the
    /// current model's datatype values hold in their fields, then one
    /// EUF-model term for every other element of the model's universe (a
    /// selector at a foreign constructor, `g(w2)`, is one: instantiating there
    /// makes the next model keep it inside the universal's range). Borrowed
    /// unchanged when no binder sort is carried. Best effort: a partial walk
    /// still yields sound instances, only never a universe.
    pub(super) fn mbqi_candidate_terms<'g>(
        &mut self,
        quants: &[TermId],
        ground_by_sort: &'g HashMap<Sort, Vec<TermId>>,
    ) -> Cow<'g, HashMap<Sort, Vec<TermId>>> {
        let mut binder_sorts: HashSet<Sort> = HashSet::default();
        for &q in quants {
            if let TermData::Forall(vars, _, _) = self.ctx.terms.get(q) {
                for (_, sort) in vars {
                    if self.is_plain_uninterpreted_sort(sort) {
                        binder_sorts.insert(sort.clone());
                    }
                }
            }
        }
        let mut carriers: Vec<TermId> = Vec::new();
        let mut carried_sorts: HashSet<Sort> = HashSet::default();
        for (sort, terms) in ground_by_sort {
            if self.declared_datatype_name(sort).is_none() {
                continue;
            }
            let carried: Vec<Sort> = binder_sorts
                .iter()
                .filter(|&b| {
                    let one: HashSet<Sort> = std::iter::once(b.clone()).collect();
                    self.sort_carries_any_of(sort, &one)
                })
                .cloned()
                .collect();
            if !carried.is_empty() {
                carriers.extend(terms);
                carried_sorts.extend(carried);
            }
        }
        if carriers.is_empty() {
            return Cow::Borrowed(ground_by_sort);
        }
        let mut candidates = ground_by_sort.clone();
        let fields = self
            .carried_binder_field_terms(&carriers, &carried_sorts, &mut Self::model_tester_holds)
            .by_sort;
        for (sort, terms) in fields {
            push_new(candidates.entry(sort).or_default(), terms);
        }
        for (sort, terms) in self.euf_universe_representatives(&carried_sorts, &candidates) {
            push_new(candidates.entry(sort).or_default(), terms);
        }
        Cow::Owned(candidates)
    }

    /// Selector terms denoting every `binder_sorts` element that the current
    /// model's values of the ground datatype terms `carriers` hold in their
    /// fields, found by following each value's constructor (a definite tester
    /// under the model) down to the binder-sort fields.
    ///
    /// Only the model's constructor is followed: a selector at another
    /// constructor reads no field of the value, and its result is whatever the
    /// selector's interpretation picks — an element the EUF universe records
    /// if a term denotes it, which [`Self::mbqi_candidate_terms`] and the gate
    /// take from there.
    ///
    /// `complete` is false when some value could not be followed exactly — an
    /// indefinite tester, a field of a non-datatype carrier sort, or the
    /// depth / size caps — and then `by_sort` names only part of the carried
    /// elements: enough for instantiation candidates, never for a universe.
    pub(in crate::executor) fn carried_binder_field_terms(
        &mut self,
        carriers: &[TermId],
        binder_sorts: &HashSet<Sort>,
        tester_holds: &mut dyn FnMut(&Self, TermId) -> Option<bool>,
    ) -> CarriedFieldTerms {
        let mut out = CarriedFieldTerms {
            by_sort: HashMap::default(),
            complete: true,
            frontier: Vec::new(),
        };
        let mut followed: HashSet<TermId> = HashSet::default();
        let mut work: Vec<(TermId, usize)> = carriers.iter().map(|&t| (t, 0)).collect();
        let mut minted = 0usize;
        while let Some((t, depth)) = work.pop() {
            if !followed.insert(t) {
                continue;
            }
            let sort = self.ctx.terms.sort(t).clone();
            let Some(constructors) = self
                .declared_datatype_name(&sort)
                .and_then(|name| self.ctx.datatype_constructors(name))
                .map(<[String]>::to_vec)
            else {
                out.complete = false;
                continue;
            };
            let mut chosen: Option<String> = None;
            for ctor in &constructors {
                let tester =
                    self.ctx
                        .terms
                        .mk_app(Symbol::named(format!("is-{ctor}")), [t], Sort::Bool);
                match tester_holds(self, tester) {
                    Some(true) => {
                        chosen = Some(ctor.clone());
                        break;
                    }
                    Some(false) => {}
                    None => break,
                }
            }
            let Some(ctor) = chosen else {
                out.complete = false;
                if depth > 0 {
                    out.frontier.push(t);
                }
                continue;
            };
            let selectors = self
                .ctx
                .constructor_selectors(&ctor)
                .unwrap_or(&[])
                .to_vec();
            let fields = self
                .ctx
                .constructor_selector_info(&ctor)
                .unwrap_or(&[])
                .to_vec();
            if selectors.len() != fields.len() {
                out.complete = false;
                continue;
            }
            for (selector, (_, field_sort)) in selectors.iter().zip(fields.iter()) {
                let direct = binder_sorts.contains(field_sort);
                if !direct && !self.sort_carries_any_of(field_sort, binder_sorts) {
                    continue;
                }
                minted += 1;
                if minted > MAX_CARRIED_FIELD_TERMS || (!direct && depth >= MAX_CARRIED_FIELD_DEPTH)
                {
                    out.complete = false;
                    return out;
                }
                let field = self.ctx.terms.mk_app(
                    Symbol::named(selector.as_str()),
                    [t],
                    field_sort.clone(),
                );
                if direct {
                    let named = out.by_sort.entry(field_sort.clone()).or_default();
                    if !named.contains(&field) {
                        named.push(field);
                    }
                } else {
                    work.push((field, depth + 1));
                }
            }
        }
        out
    }

    /// Instances that let the EPR certificate name every carried element, for
    /// MBQI to add once every candidate holds (D1). The certificate follows the
    /// datatype values of `authority_roots` by their constructors and declines
    /// when one is open — a selector chain no solver term registers,
    /// `(tl (tl (tl a1)))` below a1's third cell. Each quantifier of `quants`
    /// is instantiated at every constructor's binder-sort selector of such a
    /// value, the other binders at the first candidate of their sort; the
    /// re-solve then registers the chain and commits its constructor. Sound
    /// like every instance: a consequence of the universal. Only fresh
    /// instances (`seen`) are returned, each recorded in `provenance` (capped
    /// like the refinement's own records) when that is given.
    pub(super) fn mbqi_certificate_frontier_instances(
        &mut self,
        authority_roots: &[TermId],
        quants: &[TermId],
        candidates: &HashMap<Sort, Vec<TermId>>,
        seen: &mut HashSet<TermId>,
        mut provenance: Option<&mut Vec<crate::ematching::ForallInstantiationProvenance>>,
    ) -> Vec<TermId> {
        let mut binder_sorts: HashSet<Sort> = HashSet::default();
        for &q in quants {
            if let TermData::Forall(vars, _, _) = self.ctx.terms.get(q) {
                for (_, sort) in vars {
                    if self.is_plain_uninterpreted_sort(sort) {
                        binder_sorts.insert(sort.clone());
                    }
                }
            }
        }
        if binder_sorts.is_empty() {
            return Vec::new();
        }
        let Some(carriers) = self.binder_universe_carriers(authority_roots, &binder_sorts) else {
            return Vec::new();
        };
        if carriers.is_empty() {
            return Vec::new();
        }
        let walk = self.carried_binder_field_terms(
            &carriers,
            &binder_sorts,
            &mut Self::model_tester_holds,
        );
        let mut frontier: HashMap<Sort, Vec<TermId>> = HashMap::default();
        for t in walk.frontier {
            for (sort, field) in self.frontier_selector_terms(t, &binder_sorts) {
                push_new(frontier.entry(sort).or_default(), vec![field]);
            }
        }
        let mut out = Vec::new();
        for &q in quants {
            let TermData::Forall(vars, body, _) = self.ctx.terms.get(q).clone() else {
                continue;
            };
            for (i, (_, sort)) in vars.iter().enumerate() {
                for &field in frontier.get(sort).into_iter().flatten() {
                    let binding: Option<Vec<TermId>> = vars
                        .iter()
                        .enumerate()
                        .map(|(j, (_, s))| {
                            if j == i {
                                Some(field)
                            } else {
                                candidates.get(s).and_then(|c| c.first().copied())
                            }
                        })
                        .collect();
                    let Some(binding) = binding else { continue };
                    let subst: HashMap<String, TermId> = vars
                        .iter()
                        .zip(&binding)
                        .map(|((name, _), &t)| (name.clone(), t))
                        .collect();
                    let instance = crate::ematching::subst_vars(&mut self.ctx.terms, body, &subst);
                    if !seen.insert(instance) {
                        continue;
                    }
                    if let Some(records) = provenance.as_deref_mut() {
                        if records.len() < super::MAX_MBQI_INSTANCE_PROVENANCE_RECORDS {
                            records.push(crate::ematching::ForallInstantiationProvenance {
                                quantifier: q,
                                binding,
                                instance,
                            });
                        }
                    }
                    out.push(instance);
                }
            }
        }
        out
    }

    /// `(sel t)` for every selector, of any constructor of `t`'s datatype, whose
    /// field sort is one of `sorts`.
    fn frontier_selector_terms(&mut self, t: TermId, sorts: &HashSet<Sort>) -> Vec<(Sort, TermId)> {
        let sort = self.ctx.terms.sort(t).clone();
        let constructors = self
            .declared_datatype_name(&sort)
            .and_then(|name| self.ctx.datatype_constructors(name))
            .map(<[String]>::to_vec)
            .unwrap_or_default();
        let mut out = Vec::new();
        for ctor in constructors {
            let selectors = self
                .ctx
                .constructor_selectors(&ctor)
                .unwrap_or(&[])
                .to_vec();
            let fields = self
                .ctx
                .constructor_selector_info(&ctor)
                .unwrap_or(&[])
                .to_vec();
            for (selector, (_, field_sort)) in selectors.iter().zip(fields.iter()) {
                if sorts.contains(field_sort) {
                    let term = self.ctx.terms.mk_app(
                        Symbol::named(selector.as_str()),
                        [t],
                        field_sort.clone(),
                    );
                    out.push((field_sort.clone(), term));
                }
            }
        }
        out
    }

    /// One term per element that the current model's EUF universe records
    /// for each sort in `sorts` and that no term in `named` already denotes —
    /// the elements a selector at a foreign constructor (`g(w2)`) or a solver
    /// term put there. Deterministic: the smallest `TermId` per element.
    pub(in crate::executor) fn euf_universe_representatives(
        &self,
        sorts: &HashSet<Sort>,
        named: &HashMap<Sort, Vec<TermId>>,
    ) -> HashMap<Sort, Vec<TermId>> {
        let mut out: HashMap<Sort, Vec<TermId>> = HashMap::default();
        let Some(model) = self.last_model.as_ref() else {
            return out;
        };
        let Some(euf) = model.euf_model.as_ref() else {
            return out;
        };
        // The EUF model also keys solver-internal nodes whose ids are not in
        // the term store (sentinels near `u32::MAX`); those name nothing here.
        let store_len = self.ctx.terms.len();
        let mut by_element: Vec<(TermId, &String)> = euf
            .term_values
            .iter()
            .filter(|(t, _)| (t.0 as usize) < store_len && sorts.contains(self.ctx.terms.sort(**t)))
            .map(|(t, element)| (*t, element))
            .collect();
        by_element.sort_by_key(|(t, _)| t.0);
        for sort in sorts {
            let mut covered: HashSet<String> = HashSet::default();
            for &t in named.get(sort).into_iter().flatten() {
                if let Some(element) = euf.term_values.get(&t) {
                    covered.insert(element.clone());
                } else if let EvalValue::Element(element) = self.evaluate_term(model, t) {
                    covered.insert(element);
                }
            }
            for &(t, element) in &by_element {
                if self.ctx.terms.sort(t) == sort
                    && !contains_quantifier(&self.ctx.terms, t)
                    && covered.insert(element.clone())
                {
                    out.entry(sort.clone()).or_default().push(t);
                }
            }
        }
        out
    }
}

/// Append the terms of `new` that `list` does not hold yet, in order.
fn push_new(list: &mut Vec<TermId>, new: Vec<TermId>) {
    for t in new {
        if !list.contains(&t) {
            list.push(t);
        }
    }
}
